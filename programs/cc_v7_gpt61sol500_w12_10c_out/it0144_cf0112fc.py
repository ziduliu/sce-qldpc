    """Deterministic joint search; caching does not change its result."""
    profiles = _quotient_profiles()
    # Several label mechanisms on the strongest support profiles,
    # followed by less uniform rank-deficit experiments.
    first = profiles[:min(12, len(profiles))]
    plans = [(a, b, mode) for mode in range(3) for a, b in first]
    plans += [(a, b, 2) for a, b in profiles[len(first):]]
    bank = []
    fingerprints = set()
    z2 = (0, 0, 2)
    parity_pools = {
        p: [g for g in G.elements if g[2] % 2 == p]
        for p in (0, 1)}

    def draw_cell(rng, count, mode, ordinal):
        if mode == 0:
            return rng.sample(G.elements, count)
        if mode == 1:
            # Vary actual central-parity occupancies, not automorphism
            # images of one generator-deletion template.
            odd = (ordinal + rng.randrange(count + 1)) % (count + 1)
            return (rng.sample(parity_pools[0], count - odd)
                    + rng.sample(parity_pools[1], odd))

        # Deliberate degeneracy: complete central-involution pairs.
        # Odd cells also have an unpaired term. The quotient screen,
        # rather than a kernel screen, judges the resulting short words.
        cell = []
        while len(cell) + 2 <= count:
            g = G.pick(rng)
            h = G.mul(g, z2)
            if g not in cell and h not in cell:
                cell.extend((g, h))
        if len(cell) < count:
            cell.append(rng.choice([g for g in G.elements
                                    if g not in cell]))
        return cell

    def archived_binomial_family(A, B):
        if any(len(cell) != 2 for row in A + B for cell in row):
            return False
        # A binomial's relative central parity is gauge invariant.
        # All-odd relative labels give the parent's six inverse-pair
        # universe, already enumerated and archived.
        return all(G.mul(G.inv(cell[0]), cell[1])[2] % 2 == 1
                   for row in A + B for cell in row)

    for idx in range(N_SLOTS):
        a, b, prescribed_mode = plans[idx % len(plans)]
        rng = random.Random(BASE_SEED * 10007 + 5502400 + idx)
        best = None
        for attempt in range(112):
            # Most trials implement the prescribed mechanism. Occasional
            # unrestricted proposals keep a degenerate plan from failing
            # merely because all its paired examples have tiny logicals.
            mode = prescribed_mode if attempt % 7 else 0
            A = [[draw_cell(rng, count, mode, idx + j)
                  for j, count in enumerate(a)]]
            B = [[draw_cell(rng, count, mode, 2 * idx + j + 1)
                  for j, count in enumerate(b)]]
            if archived_binomial_family(A, B):
                continue

            hx, hz, n = lifted_matrices(G, A, B)
            rx, rz = gf2_rank(hx), gf2_rank(hz)
            k = n - rx - rz
            if k <= 0:
                continue
            px = _quotient_short_stats(hz, hx, n)
            pz = _quotient_short_stats(hx, hz, n)
            threshold = min(px[0], pz[0])

            # Only invest in the incidence fingerprint when the candidate
            # can replace the current best for this structural slot.
            score = (threshold, k, -max(px[1], pz[1]),
                     -(px[1] + pz[1]), -(px[2] + pz[2]))
            if best is not None and score <= best[0]:
                continue

            ix, iz = _quotient_incidence(hx), _quotient_incidence(hz)
            degrees = [0] * n
            for row in hx + hz:
                while row:
                    low = row & -row
                    degrees[low.bit_length() - 1] += 1
                    row ^= low
            fingerprint = (
                k, tuple(sorted((rx, rz))),
                tuple(sorted((ix, iz))),
                tuple(sorted(degrees)),
                tuple(sorted((px, pz))))
            if fingerprint in fingerprints:
                continue
            best = (score, A, B, fingerprint, px, pz)

        if best is None:
            raise ValueError("no new invariant-distinct quotient design")
        score, A, B, fingerprint, px, pz = best
