def _closed_columns(rows, n):
    """Column syndromes, taken only from the scaffold's verified lift."""
    columns = [0] * n
    for r, source in enumerate(rows):
        bit = 1 << r
        while source:
            low = source & -source
            columns[low.bit_length() - 1] |= bit
            source ^= low
    return columns


def _closed_no_two(rows, n):
    columns = _closed_columns(rows, n)
    return 0 not in columns and len(set(columns)) == n


def _closed_signature(hx, hz, n, k):
    """Uncoloured Tanner invariants: X/Z check labels are not assumed.

    Different signatures certify nonisomorphism; equal signatures are
    conservatively discarded. Rank and logical statistics alone are
    deliberately not used as the graph-separation criterion.
    """
    rows = hx + hz
    weights = [row.bit_count() for row in rows]
    neighbours = [{} for _ in rows]
    overlaps = {}
    for i, row in enumerate(rows):
        for j in range(i):
            overlap = (row & rows[j]).bit_count()
            overlaps[overlap] = overlaps.get(overlap, 0) + 1
            if overlap:
                a, b = (weights[j], overlap), (weights[i], overlap)
                neighbours[i][a] = neighbours[i].get(a, 0) + 1
                neighbours[j][b] = neighbours[j].get(b, 0) + 1
    check_profiles = tuple(sorted(
        (weights[i], tuple(sorted(profile.items())))
        for i, profile in enumerate(neighbours)))

    qubits = [[] for _ in range(n)]
    for weight, source in zip(weights, rows):
        while source:
            low = source & -source
            qubits[low.bit_length() - 1].append(weight)
            source ^= low
    qubit_profiles = tuple(sorted(tuple(sorted(p)) for p in qubits))

    moments = ()
    if k == 306:
        # Degree is an uncoloured graph invariant. Restricting the check
        # Gram matrix to the minimum-degree class remains invariant.
        # Longer closed-walk counts distinguish omitted-step geometries
        # that can share the same local overlap histogram.
        degree = min(weights)
        selected = [row for row in rows if row.bit_count() == degree]
        size = len(selected)
        gram = [[(a & b).bit_count() for b in selected]
                for a in selected]
        sparse = [[(j, value) for j, value in enumerate(row) if value]
                  for row in gram]
        power = gram
        traces = [sum(power[i][i] for i in range(size))]
        for exponent in range(2, 9):
            following = []
            for links in sparse:
                target = [0] * size
                for j, factor in links:
                    source = power[j]
                    for c, value in enumerate(source):
                        target[c] += factor * value
                following.append(target)
            power = following
            traces.append(sum(power[i][i] for i in range(size)))
        moments = tuple(traces)

    return (n, k, tuple(sorted(weights)), check_profiles,
            qubit_profiles, tuple(sorted(overlaps.items())), moments)


@lru_cache(maxsize=1)
def _closed_design_bank(G):
    """Four subgroup geometries, then fresh asymmetric support cards."""
    assert G.q == 24
    generator = (1, 0, 1)
    powers = [G.e]
    for exponent in range(1, 12):
        powers.append(G.mul(powers[-1], generator))
    assert G.mul(powers[-1], generator) == G.e
    assert len(set(powers)) == 12

    cyclic = [powers[d] for d in range(1, 6)]
    reflections = [(a, 1, 1) for a in range(3)]
    representatives = []
    for g in G.elements:
        if g == G.e or G.mul(g, g) == G.e:
            continue
        if G.idx(g) <= G.idx(G.inv(g)):
            representatives.append(g)
    assert len(representatives) == 8

    def cyclic_A(missing):
        return [[[G.e, powers[d]] for d in range(1, 6)
                 if d != missing]]

    bank, signatures = [], set()

    def finish(A, B, wanted_k):
        sa = [[len(cell) for cell in row] for row in A]
        sb = [[len(cell) for cell in row] for row in B]
        assert _grid_weights(sa, sb) <= W_MAX
        assert _no_dead_lines(sa, sb)
        assert all(len(cell) == len(set(cell))
                   for grid in (A, B) for row in grid for cell in row)

        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k != wanted_k:
            return None
        if not (_closed_no_two(hx, n) and _closed_no_two(hz, n)):
            return None
        signature = _closed_signature(hx, hz, n, k)
        if signature in signatures:
            return None

        px = _quotient_short_stats(hz, hx, n)
        pz = _quotient_short_stats(hx, hz, n)
        # A returned three is an actual logical witness weight, while
        # absence below three was exhaustively checked on both matrices.
        if min(px[0], pz[0]) != 3:
            return None
        assert css_ok(hx, hz)
        score = (9 * k, 3, k, -(px[1] + pz[1]),
                 -(px[2] + pz[2]))
        return A, B, score, px, pz, signature

    def retain(item):
        A, B, score, px, pz, signature = item
        signatures.add(signature)
        # Immutable storage keeps the cache observationally transparent.
        A = tuple(tuple(tuple(cell) for cell in row) for row in A)
        B = tuple(tuple(tuple(cell) for cell in row) for row in B)
        bank.append((A, B, score, px, pz))

    # Missing steps 1 and 5 are related by a C12 automorphism.
    # Steps 1,2,3,4 instead change the omitted graph's intrinsic geometry.
    for missing in (1, 2, 3, 4):
        if len(bank) >= N_SLOTS:
            break
        A = cyclic_A(missing)
        B = [[[G.e, g] for g in cyclic]]
        item = finish(A, B, 306)
        if item is not None:
            retain(item)

    # Four A geometries crossed with four B mechanisms:
    # 0: mixed binomial voltages, including an even-central rotation;
    # 1: cyclic binomials and a cyclic trinomial;
    # 2: mixed binomials and a noncommuting trinomial;
    # 3: three reflection voltages and one cyclic voltage.
    # Failed or invariant-colliding cards are skipped, never orbit-filled.
    for card in range(max(96, 8 * N_SLOTS)):
        if len(bank) >= N_SLOTS:
            break
        missing = 1 + card % 4
        mode = (card // 4) % 4
        local = random.Random(BASE_SEED * 10009 + 55024120 + card)
        A = cyclic_A(missing)
        best = None

        for attempt in range(48):
            if mode == 0:
                even_rotation = powers[2]
                available = [g for g in representatives
                             if g not in (even_rotation,
                                          G.inv(even_rotation))]
                steps = [even_rotation] + local.sample(available, 3)
                if not any(g[1] for g in steps):
                    continue
                row = [[G.e]] + [[G.e, g] for g in steps]
            elif mode == 1:
                steps = local.sample(cyclic, 3)
                support = local.sample(range(12), 3)
                row = ([[G.e]] + [[G.e, g] for g in steps]
                       + [[powers[d] for d in support]])
            elif mode == 2:
                steps = local.sample(representatives, 3)
                rotation = local.choice([g for g in cyclic if g[0]])
                reflection = local.choice(reflections)
                assert G.mul(rotation, reflection) != G.mul(
                    reflection, rotation)
                row = ([[G.e]] + [[G.e, g] for g in steps]
                       + [[G.e, rotation, reflection]])
            else:
                steps = reflections + [local.choice(cyclic)]
                row = [[G.e]] + [[G.e, g] for g in steps]
            B = [row]

            hx, hz, n = lifted_matrices(G, A, B)
            k = n - gf2_rank(hx) - gf2_rank(hz)
            if k != 296:
                continue
            if not (_closed_no_two(hx, n) and _closed_no_two(hz, n)):
                continue
            ix, iz = _quotient_incidence(hx), _quotient_incidence(hz)
            cost = (ix[1] + iz[1], max(ix[1], iz[1]), attempt)
            if best is not None and cost >= best[0]:
                continue
            signature = _closed_signature(hx, hz, n, k)
            if signature in signatures:
                continue
            best = (cost, B)

        if best is not None:
            item = finish(A, best[1], 296)
            if item is not None:
                retain(item)

    if len(bank) < min(5, N_SLOTS):
        raise ValueError("fewer than five fresh rank-concentrated designs")
    return tuple(bank)


def NEW_CTX(rng, G, idx):
    """Assign a subgroup/support architecture, never a relabeled fallback."""
    bank = _closed_design_bank(G)
    if idx >= len(bank):
        raise ValueError("no further invariant-distinct closed design")
    A, B, score, px, pz = bank[idx]
    return {"idx": idx, "cells": {"A": A, "B": B},
            "selection": score, "logical_screen": (px, pz)}


