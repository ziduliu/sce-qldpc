def _component_columns(rows, width):
    """Column syndromes of an extracted, verified lifted component."""
    cols = [0] * width
    for r, row in enumerate(rows):
        while row:
            bit = row & -row
            cols[bit.bit_length() - 1] |= 1 << r
            row ^= bit
    return cols


def _component_four_cycles(cols):
    seen = {}
    cycles = 0
    for syndrome in cols:
        checks = []
        while syndrome:
            bit = syndrome & -syndrome
            checks.append(bit.bit_length() - 1)
            syndrome ^= bit
        for a in range(len(checks)):
            for b in range(a):
                pair = (checks[b], checks[a])
                cycles += seen.get(pair, 0)
                seen[pair] = seen.get(pair, 0) + 1
    return cycles


def _small_logical_3(checks, stabilizers, width):
    """Exactly detect any non-stabilizer logical of weight one to three."""
    basis = {}
    for row in stabilizers:
        while row:
            p = row.bit_length() - 1
            if p not in basis:
                basis[p] = row
                break
            row ^= basis[p]

    def in_span(v):
        while v:
            p = v.bit_length() - 1
            if p not in basis:
                return False
            v ^= basis[p]
        return True

    syndromes = _component_columns(checks, width)
    singles = {}
    for i, syndrome in enumerate(syndromes):
        v = 1 << i
        if syndrome == 0 and not in_span(v):
            return True
        if syndrome in singles:
            if not in_span(v ^ singles[syndrome]):
                return True
        else:
            singles[syndrome] = v

    # After the singleton test, equal-syndrome singleton representatives
    # differ only by stabilizers, so one representative per syndrome suffices.
    for i in range(width):
        vi, si = 1 << i, syndromes[i]
        for j in range(i):
            syndrome = si ^ syndromes[j]
            v = vi | (1 << j)
            if syndrome == 0 and not in_span(v):
                return True
            if syndrome in singles:
                if not in_span(v ^ singles[syndrome]):
                    return True
    return False


def NEW_CTX(rng, G, idx):
    """Two monomial geometries, nine one-triple, nine two-triple designs."""
    design = idx % 20
    upgrades = 0 if design < 2 else (1 if design < 11 else 2)
    geometry = (design - 2) % len(_TRIPLE_GEOMETRIES)

    sa = [[1] * 7 for _ in range(2)]
    sb = [[1] * 8 for _ in range(2)]
    if upgrades:
        sa[0][0] = 3
    if upgrades == 2:
        sa[1][1] = 3
    assert _grid_weights(sa, sb) <= W_MAX
    assert _no_dead_lines(sa, sb)

    # Distinct offsets prevent parallel degree-two component columns.
    # The first two designs omit offsets at distances 1 and 3,
    # respectively, giving different missing-matching cycle structures.
    omitted_gap = (1, 3)[design] if design < 2 else 1 + design % 8
    offsets = [d for d in range(9) if d not in (0, omitted_gap)]
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE
    q = G.q
    assert q == 9
    mask = (1 << q) - 1
    pool = []
    seen = set()

    for attempt in range(72):
        ds = list(offsets)
        rng.shuffle(ds)
        A = [[[(0, 0)] for _ in range(ca)],
             [[(0, d)] for d in ds]]
        B = [[[(0, 0)] for _ in range(cb)],
             [[(0, d)] for d in range(1, 9)]]

        if upgrades:
            u = _UNITS_9[attempt % len(_UNITS_9)]
            triple = _TRIPLE_GEOMETRIES[geometry]
            A[0][0] = [(0, (u * t) % 9) for t in triple]
        if upgrades == 2:
            # A different column keeps every A-column sum at most four.
            v = _UNITS_9[(attempt // 6 + geometry) % len(_UNITS_9)]
            triple = _TRIPLE_GEOMETRIES[(geometry + 4) % 9]
            A[1][1] = [(0, (ds[1] + v * t) % 9) for t in triple]

        key = tuple(tuple(sorted(cell))
                    for grid in (A, B) for row in grid for cell in row)
        if key in seen:
            continue
        seen.add(key)
        assert all(len(cell) == len(set(cell))
                   for grid in (A, B) for row in grid for cell in row)

        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k != 283 or not (475 * n <= 1000 * k < 525 * n):
            continue

        # Extract both components only from the verified LP matrices.
        arows = []
        for i in range(ra):
            for t in range(q):
                row = hx[(i * cb) * q + t]
                arows.append(sum(
                    ((row >> (j * cb * q)) & mask) << (j * q)
                    for j in range(ca)))
        brows = [row & ((1 << (cb * q)) - 1)
                 for row in hz[:rb * q]]
        ac = _component_columns(arows, ca * q)
        bc = _component_columns(brows, cb * q)
        cycles = (_component_four_cycles(ac),
                  _component_four_cycles(bc))
        pool.append((max(cycles), sum(cycles), attempt,
                     A, B, hx, hz, n))
        if len(pool) >= 32:
            break

    pool.sort(key=lambda item: item[:3])
    for _, _, _, A, B, hx, hz, n in pool[:10]:
        if _small_logical_3(hz, hx, n):
            continue
        if _small_logical_3(hx, hz, n):
            continue
        assert css_ok(hx, hz)
        assert n - gf2_rank(hx) - gf2_rank(hz) == 283
        return {"idx": idx, "cells": {"A": A, "B": B}}

    raise ValueError("no k=283 candidate without a weight<=3 logical")


def CELL(rng, G, side, i, j, ctx):
    """Return the full selected cell without additional random draws."""
    return list(ctx["cells"][side][i][j])

