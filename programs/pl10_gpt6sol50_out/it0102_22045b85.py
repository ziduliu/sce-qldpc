GTYPE = "custom"
CUSTOM_GROUP = """
def valid_q(q):
    return q == 14

def custom_ops(q):
    # Same inversion metacyclic rule: Z_7 x| Z_2, s=6.
    m, r, s = 7, 2, 6
    els = [(a, b) for b in range(r) for a in range(m)]

    def mul(g, h):
        return ((g[0] + pow(s, g[1], m) * h[0]) % m, (g[1] + h[1]) % r)

    def inv(g):
        bi = (-g[1]) % r
        return ((-pow(s, bi, m) * g[0]) % m, bi)

    return dict(elements=els, ident=(0, 0), mul=mul, inv=inv)
"""
A0 = None                      # only used by GTYPE = "abelian"

A_SHAPE = (2, 6)               # (ra, ca)
B_SHAPE = (2, 6)               # (rb, cb); n = 40 * 14 = 560


def _verified_component_columns(rows, q, side):
    """Extract one component's columns from the verified lifted matrices."""
    columns = [0] * (6 * q)
    for i in range(2):
        for r in range(q):
            check = i * q + r
            row = rows[(i * 6 * q + r) if side == "A" else check]
            for j in range(6):
                base = j * 6 * q if side == "A" else j * q
                bits = (row >> base) & ((1 << q) - 1)
                while bits:
                    low = bits & -bits
                    columns[j * q + low.bit_length() - 1] |= 1 << check
                    bits ^= low
    return columns


def _component_defects(columns):
    """Count short component relations and pairs of shared checks."""
    singles = set(columns)
    twos = sum(col == 0 for col in columns)
    threes = fours = cycles = 0
    seen = {}
    for i, left in enumerate(columns):
        for j in range(i + 1, len(columns)):
            right = columns[j]
            syndrome = left ^ right
            twos += syndrome == 0
            threes += syndrome in singles
            previous = seen.get(syndrome)
            if previous is None:
                seen[syndrome] = (i, j)
            elif i not in previous and j not in previous:
                fours += 1
            overlap = (left & right).bit_count()
            cycles += overlap * (overlap - 1) // 2
    return twos, threes, fours, cycles


def _counts(rng, extras):
    """Two nonzero rows; doubled-cell positions are disjoint."""
    order = list(range(6))
    rng.shuffle(order)
    return [[1 + (j in order[:extras[0]]) for j in range(6)],
            [1 + (j in order[extras[0]:sum(extras)])
             for j in range(6)]]


def _draw(rng, supports):
    grid = []
    for row in supports:
        cells = []
        for count in row:
            a, parity = rng.randrange(7), rng.randrange(2)
            cell = [(a, parity)]
            if count == 2:
                # A nonidentity rotation has order seven; a mixed-coset
                # pair instead has an order-two relative element.
                cell.append(((a + rng.randrange(1, 7)) % 7, parity))
            cells.append(cell)
        grid.append(cells)
    return grid


def NEW_CTX(rng, G, idx):
    """Screen independent labels for one of twenty indexed profiles."""
    a_profiles = ((3, 3), (3, 2), (2, 3), (2, 2), (3, 1))
    b_profiles = ((3, 3), (3, 2), (2, 3), (2, 2))
    a_extras = a_profiles[idx % 5]
    b_extras = b_profiles[(idx // 5) % 4]
    best_key, best = None, None

    for _ in range(20):
        A = _draw(rng, _counts(rng, a_extras))
        B = _draw(rng, _counts(rng, b_extras))
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k <= 0:
            continue
        da = _component_defects(
            _verified_component_columns(hx, G.q, "A"))
        db = _component_defects(
            _verified_component_columns(hz, G.q, "B"))
        # k >= 238 would leave the target rate cell.
        key = (k >= 238, da[0] + db[0], da[1] + db[1],
               max(da[2], db[2]), da[2] + db[2],
               da[3] + db[3], k - 224)
        if best_key is None or key < best_key:
            best_key, best = key, {"A": A, "B": B}
    if best is None:
        raise ValueError("no positive-k filling")
    return best


def CELL(rng, G, side, i, j, ctx):
    """Return the selected complete cell for either two-row side."""
    return list(ctx[side][i][j])

