def _component_four_cycles(G, A, B):
    """Count repeated column pairs in the two lifted component Tanner graphs."""
    total = 0
    for side, cells in (("A", A), ("B", B)):
        seen = {}
        for row in cells:
            for r in G.elements:
                cols = []
                for j, cell in enumerate(row):
                    for g in cell:
                        c = G.mul(G.inv(g), r) if side == "A" else G.mul(r, g)
                        cols.append(j * G.q + G.idx(c))
                cols.sort()
                for a in range(len(cols)):
                    for b in range(a + 1, len(cols)):
                        pair = (cols[a], cols[b])
                        old = seen.get(pair, 0)
                        total += old
                        seen[pair] = old + 1
    return total


def _trial_cells(rng, idx):
    mode, placement = idx % 7, idx // 7
    u = placement % 3
    v = (placement + idx) % 3
    sa = [[2] * 3 for _ in range(2)]
    sb = [[2] * 3 for _ in range(2)]
    if mode in (1, 2, 4, 6):
        sa[0][u] = 3
    if mode in (1, 3, 5, 6):
        sb[1 if mode in (1, 6) else 0][v] = 3
    if mode == 4:
        sa[1][(u + 1) % 3] = 3
    if mode == 5:
        sb[0][(v + 1) % 3] = 3
    if mode == 6:
        sa[1][(u + 2) % 3] = 1
        sb[0][(v + 2) % 3] = 1

    def make_side(sup):
        # A frustrated sign rectangle prevents a parity-only separation.
        while True:
            signs = [rng.randrange(2) for _ in range(6)]
            differences = {signs[j] ^ signs[3 + j] for j in range(3)}
            if len(differences) > 1:
                break
        cells = []
        for i in range(2):
            row = []
            for j in range(3):
                count = sup[i][j]
                while True:
                    offsets = rng.sample(range(23), count)
                    if all(min((offsets[a] - offsets[b]) % 23,
                               (offsets[b] - offsets[a]) % 23) >= 4
                           for a in range(count) for b in range(a)):
                        break
                row.append([(a, signs[3 * i + j]) for a in offsets])
            cells.append(row)
        return cells

    return make_side(sa), make_side(sb)


def NEW_CTX(rng, G, idx):
    """Search independent fillings; only the selected complete grids are built."""
    best = None
    best_cycles = None
    for _ in range(16 + idx % 7):
        A, B = _trial_cells(rng, idx)
        cycles = _component_four_cycles(G, A, B)
        if best_cycles is None or cycles < best_cycles:
            best, best_cycles = (A, B), cycles
            if cycles == 0:
                break
    return {"A": best[0], "B": best[1]}


def CELL(rng, G, side, i, j, ctx):
    return list(ctx[side][i][j])

