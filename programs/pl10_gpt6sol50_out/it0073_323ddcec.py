A0 = None                      # only used by GTYPE = "abelian"

A_SHAPE = (1, 3)               # (ra, ca)
B_SHAPE = (1, 5)               # (rb, cb)


def _short_columns(rows, n):
    """Count zero-syndrome pairs and triples; these are screen signals."""
    columns = [0] * n
    for check, row in enumerate(rows):
        while row:
            bit = row & -row
            columns[bit.bit_length() - 1] |= 1 << check
            row ^= bit
    counts = {}
    for syndrome in columns:
        counts[syndrome] = counts.get(syndrome, 0) + 1
    pairs = sum(v * (v - 1) // 2 for v in counts.values())
    triples = 0
    for i, left in enumerate(columns):
        for right in columns[i + 1:]:
            triples += counts.get(left ^ right, 0)
    return pairs, triples // 3


def _four_cycles(rows):
    total = 0
    for i, row in enumerate(rows):
        for other in rows[:i]:
            shared = (row & other).bit_count()
            total += shared * (shared - 1) // 2
    return total


def NEW_CTX(rng, G, idx):
    """Screen an indexed trinomial geometry using the verified CSS lifts."""
    design = idx % 10
    geometry = (idx // 10 + design) % 4
    best_key, best = None, None

    for _ in range(18):
        a_steps = [1, 2, 3]
        b_steps = [1, 2, 3]
        rng.shuffle(a_steps)
        rng.shuffle(b_steps)

        def rotational_pair(step):
            first = G.pick(rng)
            return [first, G.mul(first, (step, 0))]

        A = [[rotational_pair(step) for step in a_steps]]
        B = [rotational_pair(step) for step in b_steps]
        B.append([G.pick(rng)])

        first = G.pick(rng)
        gap = 1 + design % 3
        if geometry == 0:
            # Two rotations and one reflection join the two cosets.
            relative = [(0, 0), (gap, 0), (rng.randrange(7), 1)]
        elif geometry == 1:
            # An arithmetic-progression rotational trinomial.
            relative = [(0, 0), (gap, 0), ((2 * gap) % 7, 0)]
        elif geometry == 2:
            # A non-progression rotational trinomial.
            relative = [(0, 0), (gap, 0), ((3 * gap) % 7, 0)]
        else:
            # One rotation and two reflections: a second mixed profile.
            relative = [(0, 0), (rng.randrange(7), 1),
                        (rng.randrange(7), 1)]
            while relative[1] == relative[2]:
                relative[2] = (rng.randrange(7), 1)
        triple = [G.mul(first, g) for g in relative]
        B.append(triple)
        rng.shuffle(B)
        B = [B]

        # Every line stays nonzero. HX=6+max(B)=9;
        # HZ=sum(B)+max(A)=10+2=12.
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        xp, xt = _short_columns(hz, n)
        zp, zt = _short_columns(hx, n)
        key = (k < 118, xp + zp, 2 * xp + zp,
               xt + zt, _four_cycles(hx) + _four_cycles(hz),
               abs(k - 118), rng.random())
        if best_key is None or key < best_key:
            best_key, best = key, {"A": A, "B": B}
    return best


def CELL(rng, G, side, i, j, ctx):
    """Return the screened complete cell without redrawing its terms."""
    return list(ctx[side][i][j])

