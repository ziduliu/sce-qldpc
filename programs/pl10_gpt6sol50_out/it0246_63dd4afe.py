def _component_short_cycles(G, cells, side):
    """Count rooted simple Tanner cycles of lengths four, six and eight.

    Group translation maps every lift coordinate of a given check row
    onto every other one, so one root per protograph check row suffices.
    Use the component's actual left/right lift conventions.
    """
    q = G.q
    check_vars = [[] for _ in range(len(cells) * q)]
    var_checks = [[] for _ in range(len(cells[0]) * q)]
    for i, row in enumerate(cells):
        for r in G.elements:
            check = i * q + G.idx(r)
            for j, cell in enumerate(row):
                for g in cell:
                    c = G.mul(G.inv(g), r) if side == "A" else G.mul(r, g)
                    variable = j * q + G.idx(c)
                    check_vars[check].append(variable)
                    var_checks[variable].append(check)

    adjacent = [[] for _ in check_vars]
    for check, variables in enumerate(check_vars):
        for variable in variables:
            adjacent[check].extend(
                (other, variable) for other in var_checks[variable]
                if other != check
            )

    fours = sixes = eights = 0
    identity = G.idx(G.e)
    for i in range(len(cells)):
        root = i * q + identity
        root_edges = {}
        for other, variable in adjacent[root]:
            old = root_edges.setdefault(other, [])
            fours += len(old)
            old.append(variable)

        paths = {}
        for middle, first_var in adjacent[root]:
            for end, second_var in adjacent[middle]:
                if end == root or second_var == first_var:
                    continue
                for last_var in root_edges.get(end, ()):
                    if last_var != first_var and last_var != second_var:
                        sixes += 1

                old_paths = paths.setdefault(end, [])
                for old_middle, old_first, old_second in old_paths:
                    if old_middle != middle and len({
                        first_var, second_var, old_first, old_second
                    }) == 4:
                        eights += 1
                old_paths.append((middle, first_var, second_var))
    return fours, sixes, eights


def _support_motif(idx):
    """Five genuinely different count profiles, at four indexed placements."""
    mode, position = divmod(idx % 20, 4)
    sa = [[2] * 3 for _ in range(2)]
    sb = [[2] * 4 for _ in range(3)]
    if mode == 1:
        for i in range(3):
            sb[i][(position + i) % 4] = 1
    elif mode == 2:
        for i in range(3):
            sb[i][(position + i) % 4] = 1
            sb[i][(position + i + 2) % 4] = 1
    elif mode == 3:
        for i in range(2):
            sa[i][(position + i) % 3] = 1
    elif mode == 4:
        sa[0][position % 3] = 1
        for i in range(3):
            sb[i][(position + i) % 4] = 1
    return sa, sb


def _trial_cells(rng, counts, palette):
    """Independent origins, coset signs and nonzero D16 rotation gaps."""
    rows, cols = len(counts), len(counts[0])
    while True:
        signs = [[rng.randrange(2) for _ in range(cols)]
                 for _ in range(rows)]
        if len({signs[0][j] ^ signs[1][j]
                for j in range(cols)}) == 2:
            break
    grid = []
    for i in range(rows):
        row = []
        for j in range(cols):
            start = rng.randrange(16)
            sign = signs[i][j]
            cell = [(start, sign)]
            if counts[i][j] == 2:
                gap = rng.choice(palette)
                direction = rng.choice((-1, 1))
                cell.append(((start + direction * gap) % 16, sign))
            row.append(cell)
        grid.append(row)
    return grid


def _css_four_cycles(rows):
    """Count check-pair four-cycles in a verified lifted CSS matrix."""
    total = 0
    for i, row in enumerate(rows):
        for earlier in rows[:i]:
            common = (row & earlier).bit_count()
            total += common * (common - 1) // 2
    return total


def NEW_CTX(rng, G, idx):
    """Screen complete fillings of one indexed support-and-gap motif."""
    sa, sb = _support_motif(idx)
    assert _grid_weights(sa, sb) <= W_MAX
    assert _no_dead_lines(sa, sb)

    palettes = ((1, 3, 5, 7), (1, 2, 3, 5, 7),
                (1, 2, 3, 4, 5, 6, 7),
                (2, 3, 5, 6, 7), (1, 3, 4, 5, 7))
    design = idx % 20
    pa = palettes[design // 4]
    pb = palettes[(design % 4 + 2) % len(palettes)]
    finalists = []
    for _ in range(16 + idx % 5):
        A = _trial_cells(rng, sa, pa)
        B = _trial_cells(rng, sb, pb)
        ac = _component_short_cycles(G, A, "A")
        bc = _component_short_cycles(G, B, "B")
        cycles = (max(ac[0], bc[0]), ac[0] + bc[0],
                  max(ac[1], bc[1]), ac[1] + bc[1],
                  max(ac[2], bc[2]), ac[2] + bc[2])
        finalists.append((cycles, rng.random(), A, B))
    finalists.sort(key=lambda item: item[:2])

    best_key, best = None, None
    for cycles, _, A, B in finalists[:8]:
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        cx, cz = _css_four_cycles(hx), _css_four_cycles(hz)
        # For n=576, every positive k <=71 stays below rate 0.125.
        key = (not 54 <= k <= 71, not 0 < k <= 71,
               cycles[:4], max(cx, cz), cx + cz,
               cycles[4:], abs(k - 64), rng.random())
        if best_key is None or key < best_key:
            best_key, best = key, {"A": A, "B": B}
    return best


def CELL(rng, G, side, i, j, ctx):
    return list(ctx[side][i][j])

