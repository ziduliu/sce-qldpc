GTYPE = "custom"
CUSTOM_GROUP = """
def valid_q(q):
    return q == 34

def custom_ops(q):
    els = [(a, 0) for a in range(q)]

    def red(g):
        return (g[0] % q, 0)

    def mul(g, h):
        return ((g[0] + h[0]) % q, 0)

    def inv(g):
        return ((-g[0]) % q, 0)

    return dict(elements=els, ident=(0, 0), mul=mul, inv=inv,
                idx=lambda g: g[0] % q, red=red)
"""
A0 = None                      # only used by GTYPE = "abelian"

A_SHAPE = (1, 4)               # (ra, ca)
B_SHAPE = (1, 4)               # (rb, cb)


def _component_relations(rows, bases, q):
    """Short relations among actual lifted columns of one component."""
    mask = (1 << q) - 1
    signatures = [0] * (len(bases) * q)
    for check, row in enumerate(rows[:q]):
        for j, base in enumerate(bases):
            chunk = (row >> base) & mask
            while chunk:
                bit = chunk & -chunk
                signatures[j * q + bit.bit_length() - 1] |= 1 << check
                chunk ^= bit

    singles = set(signatures)
    pairs = {}
    twos = sum(value == 0 for value in signatures)
    for i, left in enumerate(signatures):
        for right in signatures[i + 1:]:
            value = left ^ right
            twos += value == 0
            pairs[value] = pairs.get(value, 0) + 1
    triples = sum(pairs.get(value, 0) for value in singles)
    fours = sum(count * (count - 1) // 2 for count in pairs.values())
    return twos, triples, fours


def _gap_orbits_z34():
    """Four-gap spectra modulo cyclic automorphisms and gap reversal."""
    from itertools import combinations
    units = [u for u in range(1, 34, 2) if u != 17]
    representatives = set()
    for gaps in combinations(range(1, 17), 4):
        if sum(d % 2 for d in gaps) < 2:
            continue
        orbit = []
        for u in units:
            orbit.append(tuple(sorted(
                min((u * d) % 34, (-u * d) % 34) for d in gaps)))
        representatives.add(min(orbit))
    return sorted(representatives)


def NEW_CTX(rng, G, idx):
    """Compare gap-orbit pairs assigned to this slot, not their relabelings."""
    orbits = _gap_orbits_z34()
    phase, design = divmod(idx, 20)
    # The first twenty slots have all-binomial, structurally different
    # paired spectra. Later phases change the support profile as well.
    extra_a = int(phase >= 2)
    extra_b = int(phase >= 1)
    if phase >= 3:
        extra_a, extra_b = (1 + phase % 2), 1
    extra_a = min(extra_a, 2)
    extra_b = min(extra_b, 1)

    best_key, best = None, None
    q = G.q
    for trial in range(4):
        ag = orbits[(design + 20 * trial) % len(orbits)]
        bg = orbits[(design + 20 * trial + 39) % len(orbits)]
        # Different starts are gauges for binomials; the indexed gap
        # spectra, not those starts, distinguish the first 20 designs.
        def draw(gaps, extras):
            positions = set(rng.sample(range(4), extras))
            row = []
            for j, gap in enumerate(gaps):
                start = rng.randrange(q)
                terms = [(start, 0), ((start + gap) % q, 0)]
                if j in positions:
                    offset = rng.randrange(1, q)
                    while offset == gap:
                        offset = rng.randrange(1, q)
                    terms.append(((start + offset) % q, 0))
                row.append(terms)
            rng.shuffle(row)
            return [row]

        A, B = draw(ag, extra_a), draw(bg, extra_b)
        ac = [len(cell) for cell in A[0]]
        bc = [len(cell) for cell in B[0]]
        assert sum(ac) + max(bc) <= 12
        assert sum(bc) + max(ac) <= 12
        hx, hz, n = lifted_matrices(G, A, B)
        ar = _component_relations(hx, [(j * 4) * q for j in range(4)], q)
        br = _component_relations(hz, [j * q for j in range(4)], q)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        key = (k <= 0, ar[0] + br[0], ar[1] + br[1],
               ar[2] + br[2], abs(k - 314), trial)
        if best_key is None or key < best_key:
            best_key, best = key, {"A": A, "B": B}
    return best


def CELL(rng, G, side, i, j, ctx):
    """Return the complete selected cell, without redrawing its terms."""
    return list(ctx[side][i][j])

