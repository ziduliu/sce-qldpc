CONCEPT = ("In Z11 semidirect Z2 with inversion action, order 22, A=(1,4) and B=(2,6), screened A densities and distinct B inter-row voltages should reduce worst-basis circuit failures in rate cell 0.450.")
GROUP = ("Retain the metacyclic construction rule, using its order-22 dihedral instance. The related order-22 (1,3)x(2,8) bed scored 3.2; this untried shape tests a different component balance.")
SHAPES = ("A=(1,4), B=(2,6): n=572, guaranteed k=264 and rate 12/26. A has one check row and four columns; B has two check rows and six columns. Parent weight-three X witnesses occupied sector-1 Acol/Bcol blocks, especially Bcol2-3 in slot 12, without a strong check-block failure hotspot.")
FILLING = ("Twenty A-density/B-voltage designs use nonidentity rotational gaps in multi-term cells and distinct B inter-row voltages. Screen short relations on verified lifts and retain target-cell k where possible. Test against the parent's 137/500 X failures in slot 11 and 172/250 Z failures in slot 12, without rewarding excess k.")
FAMILY_NAME = "r045_m11r2s10_14x26_verified_voltage_density"

GTYPE = "custom"
CUSTOM_GROUP = """
def valid_q(q):
    return q == 22

def custom_ops(q):
    # Same metacyclic rule: Z_11 semidirect Z_2, inversion action.
    m, r, s = 11, 2, 10
    els = [(a, b) for b in range(r) for a in range(m)]

    def red(g):
        return (g[0] % m, g[1] % r)

    def mul(g, h):
        return ((g[0] + pow(s, g[1], m) * h[0]) % m,
                (g[1] + h[1]) % r)

    def inv(g):
        bi = (-g[1]) % r
        return ((-pow(s, bi, m) * g[0]) % m, bi)

    def idx(g):
        a, b = red(g)
        return b * m + a

    return dict(elements=els, ident=(0, 0), mul=mul, inv=inv,
                idx=idx, red=red)
"""
A0 = None                      # only used by GTYPE = "abelian"

A_SHAPE = (1, 4)               # (ra, ca)
B_SHAPE = (2, 6)               # (rb, cb); n = 26 * 22 = 572


def _component_defects(rows, bases, q):
    """Count short component relations in the exact lifted check rows."""
    mask = (1 << q) - 1
    columns = [0] * (len(bases) * q)
    for check, row in enumerate(rows):
        for j, base in enumerate(bases):
            bits = (row >> base) & mask
            while bits:
                low = bits & -bits
                columns[j * q + low.bit_length() - 1] |= 1 << check
                bits ^= low

    singles = {}
    for col in columns:
        singles[col] = singles.get(col, 0) + 1
    pairs = {}
    twos = threes = fours = cycles = 0
    for i, left in enumerate(columns):
        for right in columns[i + 1:]:
            syndrome = left ^ right
            twos += syndrome == 0
            threes += singles.get(syndrome, 0)
            fours += pairs.get(syndrome, 0)
            pairs[syndrome] = pairs.get(syndrome, 0) + 1
            overlap = (left & right).bit_count()
            cycles += overlap * (overlap - 1) // 2
    return twos, threes // 3, fours, cycles


def _support_design(rng, idx):
    """Four A densities crossed with five B support/voltage designs."""
    ac = list(((2, 2, 2, 2), (3, 2, 2, 2),
               (3, 3, 2, 2), (4, 2, 2, 2))[(idx // 5) % 4])
    rng.shuffle(ac)
    sa = [ac]
    sb = [[1] * 6 for _ in range(2)]
    motif = idx % 5
    if sum(ac) <= 9:
        positions = list(range(6))
        rng.shuffle(positions)
        if motif == 1:
            groups = (positions[:1], ())
        elif motif == 2:
            groups = (positions[:2], positions[2:4])
        elif motif == 3:
            groups = (positions[:3], positions[3:6])
        elif motif == 4 and sum(ac) == 8:
            groups = (positions[:2], positions[1:3])
        else:
            groups = (positions[:2], positions[2:4])
        if motif:
            for row, js in enumerate(groups):
                for j in js:
                    sb[row][j] = 2
    assert _grid_weights(sa, sb) <= W_MAX
    assert _no_dead_lines(sa, sb)
    return sa, sb


def NEW_CTX(rng, G, idx):
    """Screen independent complete fillings, using verified lift actions."""
    sa, sb = _support_design(rng, idx)
    motif = idx % 5
    rotations = [(d, 0) for d in range(11)]
    reflections = [(d, 1) for d in range(11)]
    n_rotations = (6, 0, 3, 4, 2)[motif]

    def draw_a(count):
        first = G.pick(rng)
        if count == 2:
            gap = (rng.randrange(1, 11), 0)
            return [first, G.mul(first, gap)]
        # Distinct quotient classes make denser cells connect the two
        # parity layers; rotational binomial gaps remain nonidentity.
        pool = rotations if first[1] == 0 else reflections
        other = rng.choice([g for g in pool if g != first])
        opposite = reflections if first[1] == 0 else rotations
        cell = [first, other, rng.choice(opposite)]
        if count == 4:
            cell.append(rng.choice([g for g in opposite
                                    if g != cell[2]]))
        return cell

    best_key = best = None
    q = G.q
    for _ in range(12 + idx % 5):
        A = [[draw_a(count) for count in sa[0]]]
        gaps = (rng.sample(rotations, n_rotations)
                + rng.sample(reflections, 6 - n_rotations))
        rng.shuffle(gaps)
        B = [[], []]
        for j, gap in enumerate(gaps):
            first = G.pick(rng)
            second = G.mul(first, gap)
            for row, element in enumerate((first, second)):
                cell = [element]
                if sb[row][j] == 2:
                    cell.append(G.mul(element, (rng.randrange(1, 11), 0)))
                B[row].append(cell)

        hx, hz, n = lifted_matrices(G, A, B)
        a = _component_defects(
            hx[:q], [j * B_SHAPE[1] * q for j in range(4)], q)
        b = _component_defects(
            hz[:2 * q], [j * q for j in range(6)], q)
        defects = (a[0] + b[0], a[1] + b[1],
                   max(a[2], b[2]), a[2] + b[2],
                   a[3] + b[3])
        # Verified k decides whether a screened design stays in cell 7.
        k = n - gf2_rank(hx) - gf2_rank(hz)
        key = (not 0.425 <= k / n < 0.475, defects, rng.random())
        if best_key is None or key < best_key:
            best_key, best = key, {"A": A, "B": B}
    return best


def CELL(rng, G, side, i, j, ctx):
    return list(ctx[side][i][j])

