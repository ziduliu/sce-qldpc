def _quotient_group():
    """The order-39 quotient by the central subgroup generated by y^3."""
    els = [(a, b) for b in range(3) for a in range(13)]

    def mul(g, h):
        return ((g[0] + pow(3, g[1], 13) * h[0]) % 13,
                (g[1] + h[1]) % 3)

    def inv(g):
        bi = (-g[1]) % 3
        return ((-pow(3, bi, 13) * g[0]) % 13, bi)

    return _G(dict(elements=els, ident=(0, 0), mul=mul, inv=inv), 39)


def _four_term_cell(rng, extra_class):
    """Span all action classes and all three central strata."""
    heights = rng.sample(range(3), 3)
    other = rng.choice([h for h in range(3)
                        if h != heights[extra_class]])
    b_values = [c + 3 * heights[c] for c in range(3)]
    b_values.append(extra_class + 3 * other)
    a_values = rng.sample(range(13), 4)
    cell = list(zip(a_values, b_values))
    rng.shuffle(cell)
    return cell


def _component_columns(hx, hz, q):
    """Extract sector-two A^T and B^T from the verified (2,1)x(2,1) lift."""
    mask = (1 << q) - 1
    result = []
    # Sector one has q columns. HZ's first q rows contain A^T at
    # sector-two blocks 0 and 2; HX's first q contain B^T at 0 and 1.
    for rows, bases in ((hz, (q, 3 * q)), (hx, (q, 2 * q))):
        columns = [0] * (2 * q)
        for r in range(q):
            for j, base in enumerate(bases):
                bits = (rows[r] >> base) & mask
                while bits:
                    bit = bits & -bits
                    columns[j * q + bit.bit_length() - 1] |= 1 << r
                    bits ^= bit
        result.append(columns)
    return result


def _shared_neighbour_penalty(columns):
    penalty = 0
    for i, x in enumerate(columns):
        for y in columns[:i]:
            shared = (x & y).bit_count()
            if shared >= 2:
                penalty += shared * (shared - 1) // 2
    return penalty


def _component_signatures(hx, hz, q):
    """Extract sector-two A^T and B^T checks from the verified CSS lifts."""
    rb, cb = B_SHAPE
    n1 = A_SHAPE[1] * cb * q
    a = [0] * (A_SHAPE[0] * q)
    b = [0] * (rb * q)
    for j in range(A_SHAPE[1]):
        for r in range(q):
            bits = hz[(j * rb) * q + r] >> n1
            check = 1 << (j * q + r)
            while bits:
                bit = bits & -bits
                t = bit.bit_length() - 1
                block, position = divmod(t, q)
                if block % rb == 0:
                    a[(block // rb) * q + position] |= check
                bits ^= bit
    for beta in range(cb):
        for r in range(q):
            bits = hx[beta * q + r] >> n1
            check = 1 << (beta * q + r)
            while bits:
                bit = bits & -bits
                t = bit.bit_length() - 1
                block, position = divmod(t, q)
                if block < rb:
                    b[block * q + position] |= check
                bits ^= bit
    return a, b


def _short_component_kernel(columns):
    """Return the first possible kernel weight through six, or seven."""
    length = len(columns)
    singles = set(columns)
    if 0 in singles:
        return 1
    if len(singles) != length:
        return 2
    pairs = {}
    for i in range(length):
        ci = columns[i]
        for j in range(i + 1, length):
            syndrome = ci ^ columns[j]
            if syndrome in singles:
                return 3
            if syndrome in pairs:
                return 4
            pairs[syndrome] = (i, j)
    triples = set()
    found_six = False
    for i in range(length):
        ci = columns[i]
        for j in range(i + 1, length):
            cij = ci ^ columns[j]
            for k in range(j + 1, length):
                syndrome = cij ^ columns[k]
                if syndrome in pairs:
                    return 5
                if syndrome in triples:
                    found_six = True
                else:
                    triples.add(syndrome)
    return 6 if found_six else 7


def NEW_CTX(rng, G, idx):
    """Screen distinct slot motifs, then verify rank on full order-117 lifts."""
    quotient = _quotient_group()
    signature = tuple((idx // (3 ** position)) % 3
                      for position in range(4))
    shortlist = []

    for _ in range(24):
        cells = {
            "A": [[_four_term_cell(rng, signature[i])]
                  for i in range(2)],
            "B": [[_four_term_cell(rng, signature[2 + i])]
                  for i in range(2)],
        }
        projected = {
            side: [[[(a, b % 3) for a, b in cell] for cell in row]
                   for row in cells[side]]
            for side in ("A", "B")
        }
        hx, hz, _ = lifted_matrices(
            quotient, projected["A"], projected["B"])
        acols, bcols = _component_columns(hx, hz, quotient.q)
        da = _short_component_kernel(acols)
        db = _short_component_kernel(bcols)
        penalty = (_shared_neighbour_penalty(acols)
                   + _shared_neighbour_penalty(bcols))
        grade = (min(da, db), da + db, -penalty, rng.random())
        shortlist.append((grade, cells))

    best, best_grade = None, None
    for quotient_grade, cells in sorted(
            shortlist, key=lambda item: item[0], reverse=True)[:5]:
        hx, hz, n = lifted_matrices(G, cells["A"], cells["B"])
        k = n - gf2_rank(hx) - gf2_rank(hz)
        acols, bcols = _component_columns(hx, hz, G.q)
        full_penalty = (_shared_neighbour_penalty(acols)
                        + _shared_neighbour_penalty(bcols))
        grade = (k <= 131, quotient_grade[0], quotient_grade[1],
                 -full_penalty, -abs(k - 121), quotient_grade[2])
        if best_grade is None or grade > best_grade:
            best, best_grade = cells, grade
    return best


