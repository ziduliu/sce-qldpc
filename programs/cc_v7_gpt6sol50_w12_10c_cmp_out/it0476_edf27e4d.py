def _four_term_cell(rng, extra_class, spread_mode):
    """Give each action class a term and one class an independent fourth."""
    heights = rng.sample(range(3), 3)
    b_values = [c + 3 * heights[c] for c in range(3)]
    alternatives = [extra_class + 3 * h for h in range(3)
                    if h != heights[extra_class]]
    b_values.append(rng.choice(alternatives))

    # Alternate strict and relaxed C13 difference spreads across slots.
    required_gaps = (6, 5, 6)[spread_mode]
    while True:
        a_values = rng.sample(range(13), 4)
        gaps = {
            min((a_values[i] - a_values[j]) % 13,
                (a_values[j] - a_values[i]) % 13)
            for i in range(4) for j in range(i)
        }
        if len(gaps) >= required_gaps:
            cell = list(zip(a_values, b_values))
            rng.shuffle(cell)
            return cell


def _component_columns(hx, hz, q):
    """Extract both sector-one components from the verified lift."""
    mask = (1 << q) - 1
    result = []
    # For (1,2)x(1,2), HX's first q rows expose A at sector-one
    # bases 0 and 2q; HZ's first q rows expose B at 0 and q.
    for rows, bases in ((hx, (0, 2 * q)), (hz, (0, q))):
        columns = [0] * (2 * q)
        for r in range(q):
            for j, base in enumerate(bases):
                bits = (rows[r] >> base) & mask
                while bits:
                    bit = bits & -bits
                    columns[j * q + bit.bit_length() - 1] |= 1 << r
                    bits ^= bit
        result.append(columns)
    return result


def _shared_neighbour_penalty(columns):
    penalty = 0
    for i, x in enumerate(columns):
        for y in columns[:i]:
            shared = (x & y).bit_count()
            if shared >= 2:
                penalty += shared * (shared - 1) // 2
    return penalty


def _component_signatures(hx, hz, q):
    """Extract sector-two A^T and B^T checks from the verified CSS lifts."""
    rb, cb = B_SHAPE
    n1 = A_SHAPE[1] * cb * q
    a = [0] * (A_SHAPE[0] * q)
    b = [0] * (rb * q)
    for j in range(A_SHAPE[1]):
        for r in range(q):
            bits = hz[(j * rb) * q + r] >> n1
            check = 1 << (j * q + r)
            while bits:
                bit = bits & -bits
                t = bit.bit_length() - 1
                block, position = divmod(t, q)
                if block % rb == 0:
                    a[(block // rb) * q + position] |= check
                bits ^= bit
    for beta in range(cb):
        for r in range(q):
            bits = hx[beta * q + r] >> n1
            check = 1 << (beta * q + r)
            while bits:
                bit = bits & -bits
                t = bit.bit_length() - 1
                block, position = divmod(t, q)
                if block < rb:
                    b[block * q + position] |= check
                bits ^= bit
    return a, b


def _short_component_kernel(columns):
    """Return the first possible kernel weight through six, or seven."""
    length = len(columns)
    singles = set(columns)
    if 0 in singles:
        return 1
    if len(singles) != length:
        return 2
    pairs = {}
    for i in range(length):
        ci = columns[i]
        for j in range(i + 1, length):
            syndrome = ci ^ columns[j]
            if syndrome in singles:
                return 3
            if syndrome in pairs:
                return 4
            pairs[syndrome] = (i, j)
    triples = set()
    found_six = False
    for i in range(length):
        ci = columns[i]
        for j in range(i + 1, length):
            cij = ci ^ columns[j]
            for k in range(j + 1, length):
                syndrome = cij ^ columns[k]
                if syndrome in pairs:
                    return 5
                if syndrome in triples:
                    found_six = True
                else:
                    triples.add(syndrome)
    return 6 if found_six else 7


def _has_quotient_seven(columns, q):
    """Test weight seven, using translation to fix one of two block pivots.

    This is called only after weights through six have been excluded.
    Consequently distinct triples cannot share a syndrome, so one
    representative per syndrome suffices for the disjointness test.
    """
    triples = {}
    length = len(columns)
    for i in range(length - 2):
        first = columns[i]
        ibit = 1 << i
        for j in range(i + 1, length - 1):
            partial = first ^ columns[j]
            ijbits = ibit | (1 << j)
            for k in range(j + 1, length):
                triples[partial ^ columns[k]] = ijbits | (1 << k)

    for pivot in (0, q):
        pbit = 1 << pivot
        for i in range(length - 2):
            if i == pivot:
                continue
            first = columns[pivot] ^ columns[i]
            ibits = pbit | (1 << i)
            for j in range(i + 1, length - 1):
                if j == pivot:
                    continue
                partial = first ^ columns[j]
                ijbits = ibits | (1 << j)
                for k in range(j + 1, length):
                    if k == pivot:
                        continue
                    used = ijbits | (1 << k)
                    other = triples.get(partial ^ columns[k])
                    if other is not None and not (other & used):
                        return True
    return False


def _sample_full_kernel(rng, columns):
    """Probe short component words by varied eliminations and pair sums.

    These are detected words, not a certificate of component distance.
    """
    minimum = len(columns) + 1
    hits23 = hits24 = 0
    for _ in range(10):
        order = list(range(len(columns)))
        rng.shuffle(order)
        pivots = {}
        words = []
        for j in order:
            syndrome, word = columns[j], 1 << j
            while syndrome:
                bit = syndrome.bit_length() - 1
                previous = pivots.get(bit)
                if previous is None:
                    pivots[bit] = (syndrome, word)
                    break
                syndrome ^= previous[0]
                word ^= previous[1]
            else:
                weight = word.bit_count()
                minimum = min(minimum, weight)
                hits23 += weight <= 23
                hits24 += weight == 24
                words.append(word)

        words.sort(key=int.bit_count)
        short = words[:36]
        for i, left in enumerate(short):
            for right in short[:i]:
                weight = (left ^ right).bit_count()
                if weight:
                    minimum = min(minimum, weight)
                    hits23 += weight <= 23
                    hits24 += weight == 24
    return minimum, hits23, hits24


