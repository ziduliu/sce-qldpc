def _component_columns(rows, starts, q):
    """Take component columns from the scaffold's exact lifted matrices."""
    columns = [0] * (len(starts) * q)
    mask = (1 << q) - 1
    for check, row in enumerate(rows):
        for block, start in enumerate(starts):
            bits = (row >> start) & mask
            while bits:
                bit = bits & -bits
                columns[block * q + bit.bit_length() - 1] |= 1 << check
                bits ^= bit
    return columns


def _short_relations(columns):
    """Count component relations through weight four and check-pair overlap."""
    singles = set(columns)
    pairs = {}
    twos = len(columns) - len(singles) + (0 in singles)
    threes = fours = overlaps = 0
    for i, left in enumerate(columns):
        for j in range(i):
            right = columns[j]
            syndrome = left ^ right
            threes += syndrome in singles
            fours += pairs.get(syndrome, 0)
            pairs[syndrome] = pairs.get(syndrome, 0) + 1
            shared = (left & right).bit_count()
            if shared >= 2:
                overlaps += shared * (shared - 1) // 2
    return twos, threes, fours, overlaps


def _label_cell(rng, count, mixed):
    """Give doubled cells distinct labels; vary their coset pattern."""
    if count == 1:
        return [(rng.randrange(23), rng.randrange(2))]
    if count == 2:
        a = rng.randrange(23)
        b = rng.randrange(2)
        if mixed:
            return [(a, b), (rng.randrange(23), b ^ 1)]
        return [(a, b), ((a + rng.randrange(1, 23)) % 23, b)]
    rotations = rng.sample(range(23), 2)
    reflections = rng.sample(range(23), count - 2)
    cell = [(a, 0) for a in rotations]
    cell += [(a, 1) for a in reflections]
    rng.shuffle(cell)
    return cell


def _trial_filling(rng, idx):
    """Allocate 22 or 23 B terms, enforcing both row-weight budgets."""
    heavy_count = 2 if idx % 5 == 0 else 3
    heavy = set(rng.sample(range(5), heavy_count))
    for _ in range(100):
        counts = [[1] * 5 for _ in range(3)]
        for j in range(5):
            doubled = rng.sample(range(3), 2 if j in heavy else 1)
            for i in doubled:
                counts[i][j] = 2
        if max(map(sum, counts)) <= 8:
            break
    else:
        raise ValueError("could not distribute B terms")

    a_counts = (4, 3) if (idx // 5) % 2 == 0 else (3, 4)
    A = [[_label_cell(rng, count, False) for count in a_counts]]
    B = []
    for i, row in enumerate(counts):
        B.append([
            _label_cell(rng, count,
                        count == 2 and rng.randrange(5) < idx % 4)
            for j, count in enumerate(row)
        ])
    return A, B


def NEW_CTX(rng, G, idx):
    """Compare independently labelled designs, not images of one labeling."""
    options = []
    q = G.q
    for _ in range(14):
        A, B = _trial_filling(rng, idx)
        hx, hz, _ = lifted_matrices(G, A, B)
        acol = _component_columns(
            hx[:q], [j * 5 * q for j in range(2)], q)
        bcol = _component_columns(
            hz[:3 * q], [j * q for j in range(5)], q)
        sa = _short_relations(acol)
        sb = _short_relations(bcol)
        score = (sa[0] + sb[0],
                 sa[1] + sb[1],
                 sa[2] + 3 * sb[2],
                 sa[3] + sb[3],
                 rng.random())
        options.append((score, A, B))

    fallback = None
    for score, A, B in sorted(options, key=lambda item: item[0]):
        k = lifted_k(G, A, B)
        if fallback is None or k < fallback[0]:
            fallback = (k, A, B)
        if 92 <= k <= 104:  # k/598 remains below 0.175
            return {"grid": {"A": A, "B": B}}
    return {"grid": {"A": fallback[1], "B": fallback[2]}}


