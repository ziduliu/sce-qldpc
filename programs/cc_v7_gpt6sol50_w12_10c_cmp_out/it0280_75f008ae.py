def _draw_shape_cells(rng, G, idx):
    """Twenty support/order motifs, each with independently drawn labels."""
    a_profiles = (
        (2, 2, 2, 2, 2, 2),
        (0, 2, 2, 2, 2, 2),
        (0, 2, 0, 2, 2, 2),
        (0, 2, 0, 2, 0, 2),
        (0, 0, 2, 0, 2, 0),
    )
    triple_profiles = (
        (0, 0, 1), (0, 1, 1), (0, 1, 2), (0, 1, 3),
    )
    profile = a_profiles[idx % 5]
    triple = triple_profiles[(idx // 5) % 4]

    A = []
    for i in range(2):
        row = []
        for j in range(3):
            base = G.pick(rng)
            # A relative element has order 9 or 18, never order 4.
            step = (rng.choice((1, 2, 4, 5, 7, 8)), profile[3*i+j])
            row.append([base, G.mul(base, step)])
        A.append(row)

    heavy = rng.sample(range(4), 2)
    B = [[None] * 4 for _ in range(2)]
    for i in range(2):
        for j in range(4):
            if (j in heavy) != (i == 0):
                B[i][j] = [G.pick(rng)]
