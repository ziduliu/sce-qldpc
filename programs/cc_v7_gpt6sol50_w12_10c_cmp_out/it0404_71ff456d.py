    shortlist = []

    for _ in range(34):
        cells = {
            "A": [[_four_term_cell(rng, signature[i], spread_mode)]
                  for i in range(2)],
            "B": [[_four_term_cell(rng, signature[2 + i],
                                   (spread_mode + 1) % 3)]
                  for i in range(2)],
        }
        projected = {
            side: [[[(a, b % 3) for a, b in cell] for cell in row]
                   for row in cells[side]]
            for side in ("A", "B")
        }
        hx, hz, _ = lifted_matrices(
            quotient, projected["A"], projected["B"])
        acols, bcols = _component_columns(hx, hz, quotient.q)
        da = _short_component_kernel(acols)
        db = _short_component_kernel(bcols)
        penalty = (_shared_neighbour_penalty(acols)
                   + _shared_neighbour_penalty(bcols))
        preliminary = (min(da, db), da + db, -penalty, rng.random())
        shortlist.append((preliminary, cells, acols, bcols, da, db))

    screened = []
    for _, cells, acols, bcols, da, db in sorted(
            shortlist, key=lambda entry: entry[0], reverse=True)[:12]:
        qa = (8 if da == 7
              and not _has_quotient_seven(acols, quotient.q) else da)
        qb = (8 if db == 7
              and not _has_quotient_seven(bcols, quotient.q) else db)
        penalty = (_shared_neighbour_penalty(acols)
                   + _shared_neighbour_penalty(bcols))
        quotient_grade = (min(qa, qb), qa + qb, -penalty, rng.random())
        screened.append((quotient_grade, cells, acols, bcols))

    best, best_grade = None, None
    for quotient_grade, cells, acols, bcols in sorted(
            screened, key=lambda entry: entry[0], reverse=True)[:8]:
        if quotient_grade[0] >= 8:
            hits_a = _sample_quotient_eights(rng, acols, quotient.q)
            hits_b = _sample_quotient_eights(rng, bcols, quotient.q)
        else:
            hits_a = hits_b = 100000
        hx, hz, n = lifted_matrices(G, cells["A"], cells["B"])
        k = n - gf2_rank(hx) - gf2_rank(hz)
        full_a, full_b = _component_columns(hx, hz, G.q)
        full_penalty = (_shared_neighbour_penalty(full_a)
                        + _shared_neighbour_penalty(full_b))
