def NEW_CTX(rng, G, idx):
    """Search varied legal fillings using the exact lifted matrices."""
    def supports(t):
        mode = t % 4
        if mode == 0:
            sa = [[1] * A_SHAPE[1] for _ in range(A_SHAPE[0])]
            sb = [[1] * B_SHAPE[1] for _ in range(B_SHAPE[0])]
