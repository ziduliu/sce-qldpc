def _orders(G):
    result = []
    for g in G.elements:
        h = G.e
        for t in range(1, G.q + 1):
            h = G.mul(h, g)
            if G._key(h) == G._key(G.e):
                result.append(t)
                break
        else:
            raise ValueError("element order missing")
    return result


def _designed_cell(rng, G, count, target_order, mode, orders):
    """Avoid order-two differences; prescribe binomial cycle lengths."""
    for _ in range(512):
        cell = rng.sample(G.elements, count)
        # Distinct projected permutations prevent pure-central pairs.
        if len({tuple(g[:4]) for g in cell}) != count:
            continue
        relative = [
            orders[G.idx(G.mul(G.inv(cell[a]), cell[b]))]
            for a in range(count) for b in range(a + 1, count)
        ]
        if min(relative) < 3:
            continue
        if count == 2:
            if relative[0] != target_order:
                continue
        else:
            central_span = len({g[4] for g in cell})
            wanted = 3 if mode == 0 else 2
            if central_span != wanted:
                continue
        return cell
    raise ValueError("could not realize cell design")


def _same_basis_cycles(rows):
    """Number of Tanner four-cycles within one check basis."""
    total = 0
    for i, x in enumerate(rows):
        for j in range(i):
            overlap = (x & rows[j]).bit_count()
            total += overlap * (overlap - 1) // 2
    return total


def NEW_CTX(rng, G, idx):
    """Twenty support/label briefs, screened on the actual CSS matrices."""
    profiles = (
        ((2, 2, 3), (2, 2, 2, 3)),
        ((2, 3, 3), (2, 2, 2, 3)),
        ((3, 3, 3), (2, 2, 2, 3)),
        ((1, 3, 3), (2, 2, 2, 3)),
    )
    # (A trinomial central span, B trinomial span,
    #  central coordinate of the projected order-three B difference).
    policies = ((2, 2, 0), (3, 2, 0), (2, 3, 0),
                (3, 3, 1), (1, 2, 1))
    case = idx % 20
    pa, pb = profiles[case // 5]
    aspan, bspan, three_c = policies[case % 5]
    assert _grid_weights([list(pa)], [list(pb)]) <= W_MAX

    orders = _orders(G)
    involutions = [g for g, o in zip(G.elements, orders)
                   if o == 2 and g[4] == 0]
    threes = [g for g, o in zip(G.elements, orders)
              if o == 3 and g[4] == 0]
    nonidentity = [g for g in G.elements
                   if G._key(g) != G._key(G.e)]

    def order_six(v):
        return tuple(v[:4]) + (rng.choice((1, 2)),)

    def trinomial(span):
        # Normalize one term to identity instead of searching cell
        # translations, which do not constitute new component designs.
        for _ in range(512):
            u, v = rng.sample(nonidentity, 2)
            cell = [G.e, u, v]
            if len({g[4] for g in cell}) != span:
                continue
            # Permit projected repeats and involutory trinomial ratios:
            # their actual logical and cycle consequences are screened.
            return cell
        raise ValueError("trinomial policy could not be realized")

    def census(checks, stabilizers, n):
        """Exact nontrivial logical support counts at weights 1..4."""
        pivots = {}
        for row in stabilizers:
            while row:
                p = row.bit_length() - 1
                old = pivots.get(p)
                if old is None:
                    pivots[p] = row
                    break
                row ^= old

        # Linear normal forms of unit vectors modulo the row span.
        # Each pivot row only involves lower-numbered coordinates.
        bits = [1 << i for i in range(n)]
        residues = list(bits)
        for p in sorted(pivots):
            row = pivots[p] ^ bits[p]
            residue = 0
            while row:
                bit = row & -row
                residue ^= residues[bit.bit_length() - 1]
                row ^= bit
            residues[p] = residue

        columns = [0] * n
        for r, row in enumerate(checks):
            tag = 1 << r
            while row:
                bit = row & -row
                columns[bit.bit_length() - 1] |= tag
                row ^= bit

        singles = {}
        counts = [0, 0, 0, 0]
        for a, syndrome in enumerate(columns):
            singles.setdefault(syndrome, []).append(a)
            if syndrome == 0 and residues[a]:
                counts[0] += 1

        pairs = {}
        for a in range(n):
            x, ra = columns[a], residues[a]
            for b in range(a + 1, n):
                syndrome = x ^ columns[b]
                residue = ra ^ residues[b]
                if syndrome == 0 and residue:
                    counts[1] += 1
                # The ordered partition a < b < c counts triples once.
                for c in singles.get(syndrome, ()):
                    if c > b and residue ^ residues[c]:
                        counts[2] += 1

                bucket = pairs.get(syndrome)
                if bucket is None:
                    pairs[syndrome] = [(a, b, residue)]
                else:
                    # c < d < a < b is the unique partition used here.
                    for c, d, previous in bucket:
                        if d < a and previous ^ residue:
                            counts[3] += 1
                    bucket.append((a, b, residue))
        return tuple(counts)

    best = None
    best_key = None
    for batch in range(4):
        pool = []
        for trial in range(40):
            av = rng.sample(involutions, 2)
            ar = []
            binary = 0
            for count in pa:
                if count == 1:
                    ar.append([G.e])
                elif count == 2:
                    ar.append([G.e, order_six(av[binary])])
                    binary += 1
                else:
                    ar.append(trinomial(aspan))

            bv = rng.sample(involutions, 2)
            t = rng.choice(threes)
            t = tuple(t[:4]) + (three_c,)
            B = [[[G.e, t],
                  [G.e, order_six(bv[0])],
                  [G.e, order_six(bv[1])],
                  trinomial(bspan)]]
