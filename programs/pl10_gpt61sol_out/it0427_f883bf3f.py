        opposite = [sites(row) for row in stabilizers]
        nr = len(checks)
        row_width = max(map(len, neighborhoods))
        incidence = np.full((nr, row_width), width, dtype=np.int32)
        valid = np.zeros((nr, row_width), dtype=bool)
        for r, row in enumerate(neighborhoods):
            incidence[r, :len(row)] = row
            valid[r, :len(row)] = True
        flat = incidence.ravel()
        edges = len(flat)
        degrees = np.bincount(flat[flat < width], minlength=width)
        other_degrees = np.asarray([
            column.bit_count() for column in _columns(stabilizers, width)
        ], dtype=np.int32)
        assert np.all(degrees > 0) and np.all(other_degrees > 0)

        variable_edges = np.full(
            (width, int(degrees.max())), edges, dtype=np.int32)
        used = np.zeros(width, dtype=np.int32)
        for edge, c in enumerate(flat):
            if c < width:
                variable_edges[c, used[c]] = edge
                used[c] += 1

        channel = np.random.default_rng(seed)
        levels = np.asarray((0.014, 0.022, 0.032))
        rates = np.minimum(
            0.24, levels[np.arange(shots) % 3, None]
            * (degrees + other_degrees)[None, :] / 6.0)
        errors = np.zeros((shots, width + 1), dtype=bool)
        errors[:, :width] = channel.random((shots, width)) < rates
        for shot in range(shots):
            for opportunity in range(2):
                if channel.random() < 0.30:
                    row = opposite[int(channel.integers(len(opposite)))]
                    endpoints = channel.choice(len(row), 2, replace=False)
                    for endpoint in endpoints:
                        errors[shot, row[int(endpoint)]] ^= True

        # Approximate pair exposure supplements the independent-data
        # prior. These probabilities are not inferred ASC fault rates.
        prior_rates = np.minimum(
            0.28, rates + 0.7 * other_degrees[None, :]
            / int(other_degrees.sum()))
        prior = np.zeros((shots, width + 1), dtype=np.float64)
        prior[:, :width] = np.log((1.0 - prior_rates) / prior_rates)
        target = (errors[:, incidence].sum(axis=2) & 1).astype(bool)
        target_sign = np.where(target, -1.0, 1.0)
        messages = prior[:, flat].reshape(shots, nr, row_width).copy()
        messages = np.where(valid[None, :, :], messages, 0.0)

        done = np.zeros(shots, dtype=bool)
        decoded = np.zeros((shots, width), dtype=bool)
        completion = np.full(shots, 33, dtype=np.int32)
        for iteration in range(1, 33):
            signs = np.where(messages < 0, -1.0, 1.0)
            logs = np.log(np.clip(
                np.tanh(np.abs(messages) / 2.0), 1e-12, 1.0 - 1e-7))
            logs = np.where(valid[None, :, :], logs, 0.0)
            products = np.minimum(np.exp(
                logs.sum(axis=2, keepdims=True) - logs), 1.0 - 1e-7)
            outgoing = (
                (np.log1p(products) - np.log1p(-products))
                * signs * signs.prod(axis=2, keepdims=True)
                * target_sign[:, :, None])
            outgoing = np.where(valid[None, :, :], outgoing, 0.0)
            outgoing_flat = outgoing.reshape(shots, edges)
            padded = np.zeros((shots, edges + 1), dtype=np.float64)
            padded[:, :edges] = outgoing_flat

            posterior = np.zeros((shots, width + 1), dtype=np.float64)
            posterior[:, :width] = (
                prior[:, :width] + padded[:, variable_edges].sum(axis=2))
            hard = posterior < 0
            syndrome = (hard[:, incidence].sum(axis=2) & 1).astype(bool)
            settled = np.all(syndrome == target, axis=1)
            newly = settled & ~done
            decoded[newly] = hard[newly, :width]
            completion[newly] = iteration
            done |= settled
            if np.all(done):
                break
            extrinsic = (
                posterior[:, flat] - outgoing_flat
            ).reshape(shots, nr, row_width)
            messages = np.clip(
                0.30 * messages + 0.70 * extrinsic, -24.0, 24.0)
            messages = np.where(valid[None, :, :], messages, 0.0)

        pivots = {}
        for row in stabilizers:
            while row:
                p = row.bit_length() - 1
                old = pivots.get(p)
                if old is None:
                    pivots[p] = row
                    break
                row ^= old

        def nontrivial(word):
            while word:
                p = word.bit_length() - 1
                old = pivots.get(p)
                if old is None:
                    return True
                word ^= old
            return False

        failed = ~done
        for shot in np.flatnonzero(done):
            word = 0
            for c in np.flatnonzero(errors[shot, :width] ^ decoded[shot]):
                word |= 1 << int(c)
            if nontrivial(word):
                failed[shot] = True
        return (int(np.count_nonzero(failed)),
                int(np.count_nonzero(~done)), int(completion.sum()))

