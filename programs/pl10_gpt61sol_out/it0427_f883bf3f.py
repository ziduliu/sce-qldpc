    def full_connected(rows, width):
        parent = list(range(width))

        def root(a):
            while parent[a] != a:
                parent[a] = parent[parent[a]]
                a = parent[a]
            return a

        for row in rows:
            if not row:
                continue
            bit = row & -row
            anchor = bit.bit_length() - 1
            row ^= bit
            while row:
                bit = row & -row
                a, b = root(anchor), root(bit.bit_length() - 1)
                if a != b:
                    parent[b] = a
                row ^= bit
        return len({root(a) for a in range(width)}) == 1

