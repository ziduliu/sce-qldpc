        """Degree-weighted noisy-data BP surrogate, NOT ASC memory.

        Possible opposite-check pairs are not certified ASC hooks.
        Measurement histories, gate ordering, relay BP and LSD are
        omitted. A settled residual is classified modulo the actual
        stabilizer span, rather than equating settlement with success.
        """
        import numpy as np

        def sites(row):
            out = []
            while row:
                bit = row & -row
                out.append(bit.bit_length() - 1)
                row ^= bit
            return out

