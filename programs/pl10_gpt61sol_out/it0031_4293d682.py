def _component_rows(hx, hz, q):
    """Extract components from the verified lift, never rebuild a lift."""
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE
    mask = (1 << q) - 1
    ar = []
    for i in range(ra):
        for t in range(q):
            row = hx[(i * cb) * q + t]
            ar.append(sum(((row >> (j * cb * q)) & mask) << (j * q)
                          for j in range(ca)))
    bmask = (1 << (cb * q)) - 1
    br = [row & bmask for row in hz[:rb * q]]
    return ar, br


def _four_cycles(rows):
    return sum((v * (v - 1)) // 2
               for i, row in enumerate(rows)
               for other in rows[:i]
               for v in [(row & other).bit_count()])


def _six_cycles(rows):
    """Count cycles using three checks and three distinct data columns."""
    m = len(rows)
    overlap = [[0] * m for _ in range(m)]
    for i in range(m):
        for j in range(i):
            overlap[i][j] = overlap[j][i] = (
                rows[i] & rows[j]).bit_count()
    total = 0
    for i in range(m):
        for j in range(i):
            x = overlap[i][j]
            if not x:
                continue
            common = rows[i] & rows[j]
            for h in range(j):
                y, z = overlap[j][h], overlap[i][h]
                if y and z:
                    triple = (common & rows[h]).bit_count()
                    total += x * y * z - triple * (x + y + z) + 2 * triple
    return total


def _kernel_statistics(rows, ncols):
    """Short component words and small boundaries, from verified rows.

    When column syndromes are distinct and nonzero, the normalized
    collision counts exactly count weight-three and weight-four words.
    Otherwise the duplicate statistic takes priority in the search.
    These statistics are not asserted to predict circuit pL exactly.
    """
    columns = [0] * ncols
    for r, row in enumerate(rows):
        bit = 1 << r
        while row:
            low = row & -row
            columns[low.bit_length() - 1] |= bit
            row ^= low

    singles = set(columns)
    duplicates = ncols - len(singles) + int(0 in singles)
    pairs = {}
    triples = collisions = boundary = 0
    for i, x in enumerate(columns):
        for y in columns[:i]:
            syndrome = x ^ y
            triples += int(syndrome in singles)
            old = pairs.get(syndrome, 0)
            collisions += old
            pairs[syndrome] = old + 1
            w = syndrome.bit_count()
            if w < 3:
                boundary += (3 - w) ** 2
    return duplicates, triples // 3, collisions // 3, boundary


def NEW_CTX(rng, G, idx):
    """Search and refine labels for one deliberate support architecture."""
    design = idx % len(_PROFILE_PAIRS)
    mode = (idx // len(_PROFILE_PAIRS)) % 3
    pa, pb = _PROFILE_PAIRS[design]
    counts = []

    for shape, profile in zip(
            (A_SHAPE, B_SHAPE),
            (_SUPPORT_PROFILES[pa], _SUPPORT_PROFILES[pb])):
        ra, ca = shape
        grid = [[1] * ca for _ in range(ra)]
        columns = list(range(ca))
        rng.shuffle(columns)
        cursor = 0
        for i, extra in enumerate(profile):
            for j in columns[cursor:cursor + extra]:
                grid[i][j] = 2
            cursor += extra
        counts.append(grid)

    # A rows <=9, B rows <=10, and both column totals <=3.
    # B's profile adds at most two terms to its eight-cell rows:
    # with A rows <=9, that would allow weight 13. Limit B rows to nine.
    # For profile (0,2), (1,2), or (2,2), omit one singleton in a
    # doubled row and strengthen that column in the opposite row.
    # The resulting column still has total two and neither line is dead.
    #
    # Instead use a zero at a singleton position: its opposite singleton
    # becomes a doubleton, preserving column degree two and row budgets.
    sb = counts[1]
    for i in range(2):
        while sum(sb[i]) > 9:
            j = next((j for j in range(B_SHAPE[1])
                      if sb[i][j] == 1 and sb[1 - i][j] == 1), None)
            if j is None or sum(sb[1 - i]) >= 9:
                break
            sb[i][j] = 0
            sb[1 - i][j] = 2

    # When both B rows would total ten, transfer cannot solve the total
    # budget. Remove one singleton from each row in different columns;
    # upgrade their opposite cells only if that fits the row budget.
    for i in range(2):
        while sum(sb[i]) > 9:
            j = next(j for j in range(B_SHAPE[1])
                     if sb[i][j] == 1 and sb[1 - i][j] == 1)
            sb[i][j] = 0

    assert _grid_weights(counts[0], counts[1]) <= W_MAX
    assert _no_dead_lines(counts[0], counts[1])

    def assess(A, B):
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if not (k > 0 and 19 * n <= 40 * k < 21 * n):
            return None
        ar, br = _component_rows(hx, hz, G.q)
        ast = _kernel_statistics(ar, A_SHAPE[1] * G.q)
        bst = _kernel_statistics(br, B_SHAPE[1] * G.q)
        short = tuple(v for t in range(3)
                      for v in (max(ast[t], bst[t]), ast[t] + bst[t]))
        fa, fb = _four_cycles(ar), _four_cycles(br)
        cycles = (max(fa, fb), fa + fb)
        boundary = (max(ast[3], bst[3]), ast[3] + bst[3])
        secondary = boundary + cycles if mode == 1 else cycles + boundary
        return short + secondary, hx, hz, ar, br, k

    pool = []
    for trial in range(160):
        grids = [
            [[rng.sample(G.elements, counts[s][i][j])
              for j in range(shape[1])] for i in range(shape[0])]
            for s, shape in enumerate((A_SHAPE, B_SHAPE))
        ]
        A, B = grids
        result = assess(A, B)
        if result is None:
            continue
        key, hx, hz, ar, br, k = result
        pool.append((key, trial, A, B, hx, hz, ar, br, k))
        pool.sort(key=lambda item: (item[0], item[1]))
        del pool[8:]

    if not pool:
        raise ValueError("No candidate in the 0.500 measured-rate band")

    best = None
    for key, trial, A, B, hx, hz, ar, br, k in pool:
        ua, ub = _six_cycles(ar), _six_cycles(br)
        score = key + (max(ua, ub), ua + ub)
        if best is None or score < best[0]:
            best = (score, A, B, hx, hz, k)

    # Single-label mutations preserve the deliberate support design.
    # They are accepted only after reconstructing the verified matrices.
    for step in range(64):
        score, A, B, hx, hz, k = best
        grids = [[[list(cell) for cell in row] for row in grid]
                 for grid in (A, B)]
        side = rng.randrange(2)
        shape = (A_SHAPE, B_SHAPE)[side]
        nonempty = [(i, j) for i in range(shape[0])
                    for j in range(shape[1]) if grids[side][i][j]]
        i, j = rng.choice(nonempty)
        cell = grids[side][i][j]
        position = rng.randrange(len(cell))
        alternatives = [g for g in G.elements if g not in cell]
        cell[position] = rng.choice(alternatives)
        AA, BB = grids
        result = assess(AA, BB)
        if result is None:
            continue
        key, hhx, hhz, ar, br, kk = result
        ua, ub = _six_cycles(ar), _six_cycles(br)
        candidate_score = key + (max(ua, ub), ua + ub)
        if candidate_score < score:
            best = (candidate_score, AA, BB, hhx, hhz, kk)

    score, A, B, hx, hz, k = best
    assert css_ok(hx, hz)
    return {"A": A, "B": B, "design": design,
            "k": k, "cycle_score": score}


