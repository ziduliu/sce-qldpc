def _component_checks(hx, hz, q):
    """Extract component checks from the verified full CSS construction."""
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE
    mask = (1 << q) - 1
    ac = []
    for i in range(ra):
        for t in range(q):
            full = hx[(i * cb) * q + t]
            row = 0
            for j in range(ca):
                row |= ((full >> (j * cb * q)) & mask) << (j * q)
            ac.append(row)
    bmask = (1 << (cb * q)) - 1
    bc = [hz[a * q + t] & bmask
          for a in range(rb) for t in range(q)]
    return ac, bc


def _small_component_kernel(rows, n):
    """Exactly detect a nonzero component kernel word of weight <=6.

    A collision between syndromes of subsets of size <=3 witnesses
    such a word. This is a classical component test, not a certificate
    of quantum distance or circuit-level performance.
    """
    cols = [0] * n
    for r, row in enumerate(rows):
        while row:
            bit = row & -row
            cols[bit.bit_length() - 1] |= 1 << r
            row ^= bit
    seen = {0}
    for s in cols:
        if s in seen:
            return True
        seen.add(s)
    for i, a in enumerate(cols):
        for j in range(i):
            s = a ^ cols[j]
            if s in seen:
                return True
            seen.add(s)
    for i, a in enumerate(cols):
        for j in range(i):
            ab = a ^ cols[j]
            for t in range(j):
                s = ab ^ cols[t]
                if s in seen:
                    return True
                seen.add(s)
    return False


def _same_basis_cycles(rows):
    """Four-cycle count and largest overlap between distinct checks."""
    cycles, peak = 0, 0
    for i, row in enumerate(rows):
        for j in range(i):
            overlap = (row & rows[j]).bit_count()
            cycles += overlap * (overlap - 1) // 2
            if overlap > peak:
                peak = overlap
    return cycles, peak


def _planned_labels(rng, G, idx, counts, affine):
    """Controlled quotient profiles, not automorphism copies of a seed."""
    mode = idx % 5
    phase = idx // 20
    quota = (1, 2, 3, 4, 2)[mode]
    grids = {}
    for side in ("A", "B"):
        grid = []
        width = len(counts[side][0])
        for i, crow in enumerate(counts[side]):
            row = []
            for j, weight in enumerate(crow):
                anchor = G.pick(rng)
                cell = [anchor]
                p = i * width + j
                cross = ((p + 2 * i + phase
                          + (1 if side == "B" else 0)) % 4 < quota)
                if mode == 4 and side == "B":
                    cross = not cross
                db = 1 + ((p + mode + phase) % 2) if cross else 0
                for term in range(1, weight):
                    # Trinomials use a 2+1 quotient occupancy, avoiding
                    # an imposed complete C3 orbit within one cell.
                    b = db
                    if term == 2:
                        b = db if (p + mode + phase) % 2 else 0
                        if db == 0:
                            b = 1 + ((p + mode + phase) % 2)
                    while True:
                        a = rng.randrange(7) if b else 1 + rng.randrange(6)
                        relative = affine[(a, b)]
                        if mode == 4 and (i + j + term) % 2:
                            g = G.mul(relative, anchor)
                        else:
                            g = G.mul(anchor, relative)
                        if g not in cell:
                            cell.append(g)
                            break
                row.append(cell)
            grid.append(row)
        grids[side] = grid
    return grids


def NEW_CTX(rng, G, idx):
    """Choose a screened labeling for one deliberate support design."""
    profile = (idx // 5) % 4
    mode = idx % 5
    a_profiles = (
        ((2, 2, 1, 1), (1, 1, 2, 2)),
        ((2, 2, 2, 1), (1, 1, 2, 3)),
        ((2, 2, 2, 2), (2, 2, 2, 2)),
        ((3, 1, 1, 2), (1, 2, 3, 1)),
    )
    sa = [list(row) for row in a_profiles[profile]]
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE

    if profile == 2:
        # A-row weight 8 permits B-column weight at most 4.
        threshold = 2 - min(mode, 2)
        degrees = [3 + int(j >= threshold) for j in range(cb)]
    else:
        # A-row weights 6 or 7 permit these B-column weights 4/5.
        degrees = [4 + int(j >= cb - mode) for j in range(cb)]

    sb = [[1] * cb for _ in range(rb)]
    loads = [cb] * rb
    for j, degree in enumerate(degrees):
        used = set()
        for _ in range(degree - rb):
            r = min((r for r in range(rb) if r not in used),
                    key=lambda r: (loads[r],
                                   (r - j - mode - idx // 20) % rb))
            sb[r][j] += 1
            loads[r] += 1
            used.add(r)

    # Check BOTH lifted row-weight sums before searching labels.
    assert _grid_weights(sa, sb) <= W_MAX
    assert _no_dead_lines(sa, sb)

    # Each permutation is affine x -> 2^b*x+a; this dictionary is
    # used only to select elements, never to implement a separate lift.
    slope_to_b = {1: 0, 2: 1, 4: 2}
    affine = {
        (g[0], slope_to_b[(g[1] - g[0]) % 7]): g
        for g in G.elements
    }
    counts = {"A": sa, "B": sb}
    best_key, best_cells, best_matrices = None, None, None
    clean = 0
    for trial in range(96):
        cells = _planned_labels(rng, G, idx, counts, affine)
        hx, hz, n = lifted_matrices(G, cells["A"], cells["B"])
        k = n - gf2_rank(hx) - gf2_rank(hz)
        # Guaranteed k>=84; require rate strictly below 0.175.
        if k <= 0 or 40 * k >= 7 * n:
            continue

        ac, bc = _component_checks(hx, hz, G.q)
        bad_a = _small_component_kernel(ac, ca * G.q)
        if bad_a and best_key is not None and best_key[0] == 0:
            continue
        bad_b = _small_component_kernel(bc, cb * G.q)
        penalty = 2 * int(bad_a) + int(bad_b)
        if best_key is not None and penalty > best_key[0]:
            continue

        cx, px = _same_basis_cycles(hx)
        cz, pz = _same_basis_cycles(hz)
        key = (penalty, max(px, pz), max(cx, cz), cx + cz)
        if best_key is None or key < best_key:
            best_key = key
            best_cells = cells
