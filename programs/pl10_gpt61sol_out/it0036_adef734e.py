def _short_logical_counts(checks, stabilizers, n):
    """Exact counts of nontrivial logical supports of weights 1..4.
    Matrices come exclusively from the verified scaffold lift."""
    pivots = {}
    for row in stabilizers:
        while row:
            p = row.bit_length() - 1
            old = pivots.get(p)
            if old is None:
                pivots[p] = row
                break
            row ^= old

    def nontrivial(v):
        while v:
            p = v.bit_length() - 1
            old = pivots.get(p)
            if old is None:
                return True
            v ^= old
        return False

    columns = [0] * n
    for r, row in enumerate(checks):
        syndrome_bit = 1 << r
        while row:
            bit = row & -row
            columns[bit.bit_length() - 1] |= syndrome_bit
            row ^= bit

    singles = {}
    counts = [0, 0, 0, 0]
    bits = [1 << a for a in range(n)]
    for a, syndrome in enumerate(columns):
        singles.setdefault(syndrome, []).append(a)
        if syndrome == 0 and nontrivial(bits[a]):
            counts[0] += 1

    pairs = {}
    for a in range(n):
        for b in range(a + 1, n):
            syndrome = columns[a] ^ columns[b]
            support = bits[a] | bits[b]
            if syndrome == 0 and nontrivial(support):
                counts[1] += 1

            # a < b < c counts each weight-three support once.
            for c in singles.get(syndrome, ()):
                if c > b and nontrivial(support | bits[c]):
                    counts[2] += 1

            bucket = pairs.get(syndrome)
            if bucket is None:
                pairs[syndrome] = [(a, b, support)]
            else:
                # c < d < a < b is the unique ordered partition
                # used to count each weight-four support once.
                for c, d, previous in bucket:
                    if d < a and nontrivial(previous | support):
                        counts[3] += 1
                bucket.append((a, b, support))
    return tuple(counts)


def _designed_side(rng, G, counts, side, model):
    """Singleton-free supports with four distinct ratio-order policies.

    For a single-row cyclic component, translating a whole cell is a
    column-block gauge. Fix its first term to zero instead of spending
    proposals on those relabelings.
    """
    pools = {
        35: [d for d in range(1, 18) if d % 5 and d % 7],
        7: [5, 10, 15],
        5: [7, 14],
    }
    nb = counts.count(2)
    signatures = (
        [35] * nb,
        [7] + [35] * (nb - 1),
        [5] + [35] * (nb - 1),
        [7, 5] + [35] * (nb - 2),
    )
    orders = signatures[model]
    differences = []
    for order in (35, 7, 5):
        differences.extend(rng.sample(pools[order], orders.count(order)))
    rng.shuffle(differences)
    cells = []
    t = 0
    for weight in counts:
        assert 2 <= weight <= 4
        if weight == 2:
            # d in 1..17 identifies an undirected C35 edge type.
            cell = [G.e, (differences[t],)]
            t += 1
        else:
            cell = [G.e] + rng.sample(G.elements[1:], weight - 1)
        cells.append(cell)
    return [cells]


def _c35_components(hx, hz, q):
    """Extract both components exclusively from the verified CSS lift."""
    mask = (1 << q) - 1
    # X checks at B-column zero contain the A-left component.
    ar = [
        sum(((hx[t] >> (j * 4 * q)) & mask) << (j * q)
            for j in range(4))
        for t in range(q)
    ]
    # Z checks at A-column zero contain the B-right component.
    bmask = (1 << (4 * q)) - 1
    br = [hz[t] & bmask for t in range(q)]
    return ar, br


def NEW_CTX(rng, G, idx):
    """Twenty count/order architectures; optimize labels within each."""
    profiles = (
        ((2, 2, 2, 2), (2, 2, 2, 2)),
        ((2, 2, 2, 2), (2, 2, 2, 3)),
        ((2, 2, 2, 2), (2, 2, 3, 3)),
        ((2, 2, 2, 2), (2, 2, 2, 4)),
        ((2, 2, 2, 3), (2, 2, 2, 3)),
    )
    case = idx % 20
    ac, bc = profiles[case // 4]
    model = case % 4
    sa, sb = [list(ac)], [list(bc)]
    assert _no_dead_lines(sa, sb)
    assert _grid_weights(sa, sb) <= 12
    assert _grid_weights(sa, sb) <= W_MAX

    # Extra harness slots independently optimize the architectures;
    # they are never constructed by applying saved-code automorphisms.
    pool = []
    for attempt in range(48):
        A = _designed_side(rng, G, ac, "A", model)
        B = _designed_side(rng, G, bc, "B", model)
        hx, hz, n = lifted_matrices(G, A, B)
        ar, br = _c35_components(hx, hz, G.q)

        # With an empty stabilizer span these are exact classical
        # kernel-support counts, not quantum logical classifications.
        a = _short_logical_counts(ar, [], 4 * G.q)
        b = _short_logical_counts(br, [], 4 * G.q)
        key = (
            a[0] + b[0],
            a[1] + b[1],
            max(a[2], b[2]),
            a[2] + b[2],
            max(a[3], b[3]),
            a[3] + b[3],
        )
        pool.append((key, attempt, A, B, hx, hz, n))
        pool.sort(key=lambda item: (item[0], item[1]))
        del pool[3:]

    best = None
    for component_key, attempt, A, B, hx, hz, n in pool:
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k <= 0 or 40 * k <= 21 * n:
            continue
        x = _short_logical_counts(hz, hx, n)
        z = _short_logical_counts(hx, hz, n)
        edges = sum(row.bit_count() for row in hx + hz)
        key = (
            x[0] + z[0],
            x[1] + z[1],
            max(x[2], z[2]),
            x[2] + z[2],
            max(x[3], z[3]),
            x[3] + z[3],
            edges,
            component_key,
            attempt,
        )
        if best is None or key < best[0]:
            best = (key, A, B, hx, hz, k)

    if best is None:
        raise ValueError("no positive-k target-cell filling")
    key, A, B, hx, hz, k = best
    assert css_ok(hx, hz)
    return {"idx": idx, "case": case, "k": k,
            "screen": key, "cells": {"A": A, "B": B}}


