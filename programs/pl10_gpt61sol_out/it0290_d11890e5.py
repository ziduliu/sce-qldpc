def _component_rows(hx, hz, q):
    """Extract components from the verified lift, never rebuild a lift."""
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE
    mask = (1 << q) - 1
    ar = []
    for i in range(ra):
        for t in range(q):
            row = hx[(i * cb) * q + t]
            ar.append(sum(((row >> (j * cb * q)) & mask) << (j * q)
                          for j in range(ca)))
    bmask = (1 << (cb * q)) - 1
    br = [row & bmask for row in hz[:rb * q]]
    return ar, br


def _four_cycles(rows):
    return sum((v * (v - 1)) // 2
               for i, row in enumerate(rows)
               for other in rows[:i]
               for v in [(row & other).bit_count()])


def _six_cycles(rows):
    """Count cycles using three checks and three distinct data columns."""
    m = len(rows)
    overlap = [[0] * m for _ in range(m)]
    for i in range(m):
        for j in range(i):
            overlap[i][j] = overlap[j][i] = (
                rows[i] & rows[j]).bit_count()
    total = 0
    for i in range(m):
        for j in range(i):
            x = overlap[i][j]
            if not x:
                continue
            common = rows[i] & rows[j]
            for h in range(j):
                y, z = overlap[j][h], overlap[i][h]
                if y and z:
                    triple = (common & rows[h]).bit_count()
                    total += x * y * z - triple * (x + y + z) + 2 * triple
    return total


def _kernel_statistics(rows, ncols):
    """Short component words and small boundaries, from verified rows.

    When column syndromes are distinct and nonzero, the normalized
    collision counts exactly count weight-three and weight-four words.
    Otherwise the duplicate statistic takes priority in the search.
    These statistics are not asserted to predict circuit pL exactly.
    """
    columns = [0] * ncols
    for r, row in enumerate(rows):
        bit = 1 << r
        while row:
            low = row & -row
            columns[low.bit_length() - 1] |= bit
            row ^= low

    singles = set(columns)
    duplicates = ncols - len(singles) + int(0 in singles)
    pairs = {}
    triples = collisions = boundary = 0
    for i, x in enumerate(columns):
        for y in columns[:i]:
            syndrome = x ^ y
            triples += int(syndrome in singles)
            old = pairs.get(syndrome, 0)
            collisions += old
            pairs[syndrome] = old + 1
            w = syndrome.bit_count()
            if w < 3:
                boundary += (3 - w) ** 2
    return duplicates, triples // 3, collisions // 3, boundary


def _retired_unitrow_ctx(rng, G, idx):
    """Inactive order-eight experiment; never called on the new bed."""
    from itertools import combinations

    # Entries count second-row binomials/trinomials on A and B.
    # Each side also has one zero second-row cell at column zero.
    profiles = (
        tuple((a2, 0, b2, 0)
              for a2 in range(4) for b2 in range(3))
        + tuple((a2, 0, 0, 1) for a2 in range(3))
        + tuple((a2, 1, b2, 0)
                for a2 in range(2) for b2 in range(2))
        + ((0, 2, 0, 0),)
    )
    design = idx % len(profiles)
    ratio_mode = (idx // len(profiles)) % 3
    a2, a3, b2, b3 = profiles[design]

    def support(width, doubles, triples):
        lower = ([0] + [2] * doubles + [3] * triples
                 + [1] * (width - 1 - doubles - triples))
        return [[1] * width, lower]

    sa = support(A_SHAPE[1], a2, a3)
    sb = support(B_SHAPE[1], b2, b3)
    assert len(profiles) == 20
    assert _grid_weights(sa, sb) <= min(12, W_MAX)
    assert _no_dead_lines(sa, sb)

    # Fix upper cells to the identity instead of drawing column gauges.
    # Lower monomials are distinct; equal-weight lower cells are sampled
    # without replacement. No slot is made by relabeling a saved code.
    pairs = []
    for g, h in combinations(G.elements, 2):
        d = G.mul(G.inv(g), h)
        involutory = G._key(G.mul(d, d)) == G._key(G.e)
        if ratio_mode == 0 and involutory:
            continue
        if ratio_mode == 2 and not involutory:
            continue
        pairs.append((g, h))
    triples = list(combinations(G.elements, 3))

    def draw(weights):
        lower_weights = weights[1]
        cells = {
            1: [[g] for g in rng.sample(
                G.elements, lower_weights.count(1))],
            2: [list(p) for p in rng.sample(
                pairs, lower_weights.count(2))],
            3: [list(p) for p in rng.sample(
                triples, lower_weights.count(3))],
        }
        lower = [cells[w].pop() if w else [] for w in lower_weights]
        return [[[G.e] for _ in weights[0]], lower]

    def assess(A, B):
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k != 240:
            return None
        ar, br = _component_rows(hx, hz, G.q)
        ast = _kernel_statistics(ar, A_SHAPE[1] * G.q)
        bst = _kernel_statistics(br, B_SHAPE[1] * G.q)
        if ast[0] or bst[0] or ast[1] or bst[1]:
            return None
        fa, fb = _four_cycles(ar), _four_cycles(br)
        key = (max(ast[2], bst[2]), ast[2] + bst[2],
               max(fa, fb), fa + fb,
               max(ast[3], bst[3]), ast[3] + bst[3])
        return key, hx, hz, n

    def columns(rows, n):
        out = [0] * n
        for r, row in enumerate(rows):
            marker = 1 << r
            while row:
                bit = row & -row
                out[bit.bit_length() - 1] |= marker
                row ^= bit
        return out

    def logical_risk(checks, stabilizers, n):
        """Exact <=4 support classification; circuit costs are surrogates.

        Pair partitions count shared-check ancilla-spread opportunities.
        They do not assert that ASC realizes any particular hook order.
        """
        syndrome = columns(checks, n)
        spread = columns(stabilizers, n)
        exposure = [a.bit_count() + b.bit_count()
                    for a, b in zip(syndrome, spread)]

        pivots = {}
        for row in stabilizers:
            while row:
                p = row.bit_length() - 1
                old = pivots.get(p)
                if old is None:
                    pivots[p] = row
                    break
                row ^= old

        cache = {}

        def nontrivial(word):
            answer = cache.get(word)
            if answer is not None:
                return answer
            reduced = word
            while reduced:
                p = reduced.bit_length() - 1
                old = pivots.get(p)
                if old is None:
                    cache[word] = True
                    return True
                reduced ^= old
            cache[word] = False
            return False

        bits = [1 << i for i in range(n)]
        singles = {}
        for i, s in enumerate(syndrome):
            if s == 0 and nontrivial(bits[i]):
                return None
            singles.setdefault(s, []).append(i)

        pair_buckets = {}
        hook_one = weighted_two = hook_two = quartets = 0
        hits = [0] * n
        for i in range(n):
            si, bi = syndrome[i], bits[i]
            for j in range(i):
                s = si ^ syndrome[j]
                word = bi | bits[j]
                if s == 0 and nontrivial(word):
                    return None
                for t in singles.get(s, ()):
                    if t != i and t != j:
                        if nontrivial(word | bits[t]):
                            return None

                hooks = (spread[i] & spread[j]).bit_count()
                weight = exposure[i] * exposure[j]
                bucket = pair_buckets.get(s)
                if bucket is None:
                    pair_buckets[s] = [(word, hooks, weight)]
                    continue

                for other, other_hooks, other_weight in bucket:
                    if word & other:
                        continue
                    quartet = word | other
                    fresh = quartet not in cache
                    if not nontrivial(quartet):
                        continue
                    # Each quartet has three disjoint pair partitions.
                    # Across them these sums visit its six pairs once.
                    hook_one += hooks + other_hooks
                    weighted_two += weight + other_weight
                    hook_two += hooks * other_hooks
                    if fresh:
                        quartets += 1
                        remaining = quartet
                        while remaining:
                            bit = remaining & -remaining
                            hits[bit.bit_length() - 1] += 1
                            remaining ^= bit
                bucket.append((word, hooks, weight))

        return hook_one, weighted_two, hook_two, quartets, max(hits)

    # Cheap component screening precedes the more expensive quantum
    # classification. Retain distinct relative-label proposals.
    pool = []
    seen = set()
    for trial in range(192):
        A, B = draw(sa), draw(sb)
        signature = tuple(
            tuple(sorted(G.idx(g) for g in cell))
            for grid in (A, B) for row in grid for cell in row)
        if signature in seen:
            continue
        seen.add(signature)
        result = assess(A, B)
        if result is None:
            continue
        key, hx, hz, n = result
        pool.append((key, trial, A, B, hx, hz, n))
        pool.sort(key=lambda item: (item[0], item[1]))
        del pool[12:]

    best = None
    for component_key, trial, A, B, hx, hz, n in pool:
        pz = logical_risk(hx, hz, n)
        if pz is None:
            continue
        px = logical_risk(hz, hx, n)
        if px is None:
            continue
        # Minimax protects the weaker basis. Gate exposure weights the
        # two-data-fault ambiguities; shared ancillas identify possible
        # lower-order spread faults without claiming a circuit simulation.
        score = tuple(v for t in range(5)
                      for v in (max(px[t], pz[t]), px[t] + pz[t]))
        score += component_key
        if best is None or score < best[0]:
            best = (score, A, B, hx, hz)

    if best is None:
        raise ValueError("No target-rate filling passed quantum <=3 screen")
    score, A, B, hx, hz = best
    assert css_ok(hx, hz)
    assert max(row.bit_count() for row in hx + hz) <= W_MAX
    return {"A": A, "B": B, "design": design, "ratio_mode": ratio_mode,
            "k": 240, "circuit_risk": score}


def _mixed_columns(rows, width):
    """Transpose only helper-built or verified-action-composed rows."""
    result = [0] * width
    for r, row in enumerate(rows):
        while row:
            bit = row & -row
            result[bit.bit_length() - 1] |= 1 << r
            row ^= bit
    return result


def _mixed_quotient(rows, width):
    """Linear canonical remainders modulo the actual stabilizer span."""
    pivots = {}
    for row in rows:
        while row:
            p = row.bit_length() - 1
            old = pivots.get(p)
            if old is None:
                pivots[p] = row
                break
            row ^= old
    result = [0] * width
    for c in range(width):
        row = pivots.get(c)
        if row is None:
            result[c] = 1 << c
            continue
        tail, value = row ^ (1 << c), 0
        while tail:
            bit = tail & -tail
            value ^= result[bit.bit_length() - 1]
            tail ^= bit
        result[c] = value
    return result


def _mixed_low4(checks, stabilizers, width):
    """Exact existence test for quantum logicals of weight at most four."""
    cols = _mixed_columns(checks, width)
    residual = _mixed_quotient(stabilizers, width)
    seen = {0: 0}
    for c, syndrome in enumerate(cols):
        label = residual[c]
        previous = seen.get(syndrome)
        if previous is not None and previous != label:
            return True
        seen[syndrome] = label
    for c, syndrome in enumerate(cols):
        for d in range(c):
            value = syndrome ^ cols[d]
            label = residual[c] ^ residual[d]
            previous = seen.get(value)
            if previous is not None and previous != label:
                return True
            seen[value] = label
    return False


def _mixed_bp_probe(checks, stabilizers, width, seed):
    """Noisy-data decoder surrogate, NOT the measured ASC experiment.

    Possible spread pairs are sampled without asserting an ASC ordering.
    Measurement histories, relay BP and LSD are deliberately omitted.
    """
    import numpy as np

    def sites(row):
        out = []
        while row:
            bit = row & -row
            out.append(bit.bit_length() - 1)
            row ^= bit
        return out

    neighbors = [sites(row) for row in checks]
    opposite = [sites(row) for row in stabilizers]
    incident = [[] for _ in range(width)]
    variables = []
    for row in neighbors:
        for c in row:
            incident[c].append(len(variables))
            variables.append(c)
    ne = len(variables)
    nr = len(neighbors)
    max_check = max(map(len, neighbors))
    max_variable = max(map(len, incident))
    check_edges = np.full((nr, max_check), ne, dtype=np.int32)
    check_sites = np.zeros((nr, max_check), dtype=np.int32)
    valid = np.zeros((nr, max_check), dtype=bool)
    offset = 0
    for r, row in enumerate(neighbors):
        degree = len(row)
        check_edges[r, :degree] = np.arange(offset, offset + degree)
        check_sites[r, :degree] = row
        valid[r, :degree] = True
        offset += degree
    variable_edges = np.full(
        (width, max_variable), ne, dtype=np.int32)
    for c, edges in enumerate(incident):
        variable_edges[c, :len(edges)] = edges
    variables = np.asarray(variables, dtype=np.int32)

    shots = 48
    sensed = np.asarray([len(v) for v in incident], dtype=float)
    spread = np.asarray([
        s.bit_count() for s in _mixed_columns(stabilizers, width)
    ], dtype=float)
    levels = np.asarray((0.012, 0.022, 0.036))
    rates = np.minimum(
        0.22, levels[np.arange(shots) % 3, None]
        * (sensed + spread)[None, :] / 6.0)
    channel = np.random.RandomState(seed)
    errors = channel.random_sample((shots, width)) < rates
    triggers = channel.random_sample(
        (shots, len(opposite))) < 0.003
    for shot, r in zip(*np.nonzero(triggers)):
        row = opposite[int(r)]
        if len(row) >= 2:
            a, b = channel.choice(len(row), 2, replace=False)
            errors[shot, row[int(a)]] ^= True
            errors[shot, row[int(b)]] ^= True

    mean_weight = sum(map(len, opposite)) / len(opposite)
    prior = np.minimum(
        0.25, rates + 0.006 * spread[None, :] / mean_weight)
    llr = np.log((1.0 - prior) / prior)
    target = np.logical_xor.reduce(
        errors[:, check_sites] & valid[None, :, :], axis=2)
    target_sign = np.where(target, -1.0, 1.0)
    messages = llr[:, variables].copy()
    outgoing = np.zeros((shots, ne + 1), dtype=float)
    done = np.zeros(shots, dtype=bool)
    decoded = np.zeros((shots, width), dtype=bool)
    completion = np.full(shots, 49, dtype=np.int32)
    positions = np.arange(max_check)[None, None, :]

    for iteration in range(48):
        padded = np.concatenate(
            (messages, np.zeros((shots, 1))), axis=1)
        shaped = padded[:, check_edges]
        magnitude = np.where(
            valid[None, :, :], np.abs(shaped), np.inf)
        signs = np.where(shaped < 0.0, -1.0, 1.0)
        product = np.prod(signs, axis=2) * target_sign
        minimum_at = np.argmin(magnitude, axis=2)
        smallest = np.partition(magnitude, 1, axis=2)[:, :, :2]
        size = np.where(
            positions == minimum_at[:, :, None],
            smallest[:, :, 1, None], smallest[:, :, 0, None])
        update = 0.80 * product[:, :, None] * signs * size
        update = np.where(valid[None, :, :], update, 0.0)
        outgoing[:, :ne] = update[:, valid]
        posterior = llr + outgoing[:, variable_edges].sum(axis=2)
        hard = posterior < 0.0
        parity = np.logical_xor.reduce(
            hard[:, check_sites] & valid[None, :, :], axis=2)
        settled = ~np.any(parity != target, axis=1)
        newly = settled & ~done
        decoded[newly] = hard[newly]
        completion[newly] = iteration + 1
        done |= settled
        if np.all(done):
            break
        proposal = posterior[:, variables] - outgoing[:, :ne]
        messages = (0.30 * messages
                    + 0.70 * np.clip(proposal, -24.0, 24.0))

    residual = _mixed_quotient(stabilizers, width)
    failed = ~done
    logical_weight = 0
    for shot in np.flatnonzero(done):
        difference = decoded[shot] ^ errors[shot]
        label = 0
        for c in np.flatnonzero(difference):
            label ^= residual[int(c)]
        if label:
            failed[shot] = True
            logical_weight += int(np.count_nonzero(difference))
    return (int(np.count_nonzero(failed)),
            int(np.count_nonzero(~done)),
            logical_weight, int(completion.sum()))


