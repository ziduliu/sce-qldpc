    def clone(grid):
        return [[list(cell) for cell in row] for row in grid]

    def component(grid, side):
        rows = [0] * (len(grid) * q)
        for i, row in enumerate(grid):
            for j, cell in enumerate(row):
                for g in cell:
                    block = actions[side][G.idx(g)]
                    for t, bits in enumerate(block):
                        rows[i * q + t] ^= bits << (j * q)
        return rows

    def directions(values):
        return {
            min((a - b) % q, (b - a) % q)
            for a, b in combinations(values, 2)
        }

    def draw_cell(side, i, j):
        weight = supports[side][i][j]
        if not weight:
            return []
        if weight < 3:
            return rng.sample(G.elements, weight)
        if weight == 4:
            # A (13,4,1) cyclic difference set: all six undirected
            # internal directions occur exactly once.
            u, origin = rng.randrange(1, q), rng.randrange(q)
            return [((origin + u * a) % q,) for a in (0, 1, 3, 9)]
        for attempt in range(128):
            values = rng.sample(range(q), 3)
            if len(directions(values)) == 3:
                return [(a,) for a in values]
        raise ValueError("Sidon trinomial draw exhausted")

    def draw(side):
        return [[draw_cell(side, i, j)
                 for j in range(len(row))]
                for i, row in enumerate(supports[side])]

    def exact56(cols):
        """Exact weight-five/six counts when weights <=4 are absent."""
        pairs = {cols[i] ^ cols[j]
                 for i in range(len(cols)) for j in range(i)}
        triples = {}
        five = six = boundary = 0
        for i, x in enumerate(cols):
            for j in range(i):
                pair = x ^ cols[j]
                for h in range(j):
                    value = pair ^ cols[h]
                    five += int(value in pairs)
                    old = triples.get(value, 0)
                    six += old
                    triples[value] = old + 1
                    w = value.bit_count()
                    if w <= 4:
                        boundary += (5 - w) ** 2
        assert five % 10 == 0 and six % 10 == 0
        return five // 10, six // 10, boundary

    def witness_scan(cols, side):
        """Sample actual component words; results are upper bounds only."""
        source = random.Random(
            1303517 + 65537 * idx + int(side == "B"))
        order = list(range(len(cols)))
        minimum = len(cols) + 1
        short = set()
        for trial in range(40):
            source.shuffle(order)
            pivots, basis = {}, []
            for c in order:
                syndrome, word = cols[c], 1 << c
                while syndrome:
                    p = syndrome.bit_length() - 1
                    old = pivots.get(p)
                    if old is None:
                        pivots[p] = (syndrome, word)
                        break
                    syndrome ^= old[0]
                    word ^= old[1]
                if not syndrome:
                    basis.append(word)
            for sweep in range(2):
                source.shuffle(basis)
                for i, word in enumerate(basis):
                    weight = word.bit_count()
                    minimum = min(minimum, weight)
                    if weight <= 10:
                        short.add(word)
                    for other in basis[:i]:
                        value = word ^ other
                        if not value:
                            continue
                        w = value.bit_count()
                        minimum = min(minimum, w)
                        if w <= 10:
                            short.add(value)
                        if w < weight:
                            word, weight = value, w
                    basis[i] = word
            if minimum <= 6:
                break
        vulnerable = sum(word.bit_count() <= 8 for word in short)
        return minimum, vulnerable

    def portfolio(side):
        grid_support = supports[side]
        width = len(grid_support[0]) * q
        sites = [(i, j) for i, row in enumerate(grid_support)
                 for j, count in enumerate(row) if count]
        pool, seen = [], set()
        serial = 0

        def analyze(grid):
            rows = component(grid, side)
            deficit = len(rows) - gf2_rank(rows)
            four, six = _four_cycles(rows), _six_cycles(rows)
            energy = 200 * deficit + (80 * four + six / 8.0) / q
            return energy, rows, deficit, four, six

        def retain(grid, result):
            nonlocal serial
            _, rows, deficit, four, six = result
            stats = _kernel_statistics(rows, width)
            # Equal measured component statistics are conservatively
            # collapsed within this shortlist, not counted as diversity.
            invariant = (deficit, stats[:3], four, six)
            if invariant in seen:
                return
            seen.add(invariant)
            serial += 1
            key = (deficit,) + stats[:3] + (four, six, stats[3])
            pool.append((key, serial, clone(grid), list(rows)))
            pool.sort(key=lambda entry: entry[:2])
            del pool[8:]

        for restart in range(3):
            grid = draw(side)
            current = analyze(grid)
            retain(grid, current)
            local_grid, local = clone(grid), current
            for step in range(320):
                i, j = rng.choice(sites)
                old = grid[i][j]
                if rng.random() < 0.30:
                    shift = rng.randrange(1, q)
                    grid[i][j] = [((g[0] + shift) % q,) for g in old]
                else:
                    grid[i][j] = draw_cell(side, i, j)
                proposed = analyze(grid)
                delta = proposed[0] - current[0]
                temperature = 10.0 * (0.987 ** step) + 0.08
                if delta <= 0 or rng.random() < math.exp(
                        -min(700.0, delta / temperature)):
                    current = proposed
                    if current[0] < local[0]:
                        local_grid, local = clone(grid), current
                    if step % 40 == 39:
                        retain(grid, current)
                else:
                    grid[i][j] = old
            retain(local_grid, local)
            retain(grid, current)

        finalists = []
        for coarse, serial, grid, rows in pool:
            if coarse[0]:
                continue
            cols = _mixed_columns(rows, width)
            small = coarse[1:4]
            five, six, boundary = (
                exact56(cols) if not any(small)
                else (10**9, 10**9, 10**9))
            distance, vulnerable = witness_scan(cols, side)
            key = (int(any(small)), int(bool(five or six)),
                   max(0, 8 - distance), sum(small),
                   five + six, vulnerable, boundary,
                   coarse[4], coarse[5])
            finalists.append((key, grid, rows))
        finalists.sort(key=lambda entry: entry[0])
        return finalists[:4]

    apool, bpool = portfolio("A"), portfolio("B")
    proposals = []
    for ak, A, ar in apool:
        for bk, B, br in bpool:
            key = tuple(value for a, b in zip(ak, bk)
                        for value in (max(a, b), a + b))
            proposals.append((key, A, B, ar, br))
    proposals.sort(key=lambda entry: entry[0])

    prepared = []
    for coarse, A, B, ar, br in proposals:
        hx, hz, n = lifted_matrices(G, A, B)
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if n != 598 or k != 195:
            continue
        actual_a, actual_b = _component_rows(hx, hz, q)
        assert actual_a == ar and actual_b == br
        assert css_ok(hx, hz)
        assert max(row.bit_count() for row in hx + hz) <= W_MAX
        low = int(_mixed_low4(hx, hz, n))
        low += int(_mixed_low4(hz, hx, n))
        prepared.append((low, coarse, A, B, hx, hz))
        if len(prepared) == 6:
            break
    if not prepared:
        raise ValueError("No full-rank mixed-degree C13 filling")
    prepared.sort(key=lambda entry: entry[:2])

    best = None
    for low, coarse, A, B, hx, hz in prepared[:3]:
        # Common channel seeds across joint alternatives within a basis.
        bx = _mixed_bp_probe(hz, hx, 598, 13035031 + 1009 * idx)
        bz = _mixed_bp_probe(hx, hz, 598, 13035032 + 1009 * idx)
        key = (
            low, coarse[0], coarse[2], coarse[4],
            max(bx[0], bz[0]), bx[0] + bz[0],
            max(bx[1], bz[1]), bx[1] + bz[1],
            bx[2] + bz[2], bx[3] + bz[3], coarse)
        if best is None or key < best[0]:
            best = (key, A, B, hx, hz, bx, bz)

    key, A, B, hx, hz, bx, bz = best
    assert lifted_k(G, A, B) == 195
    assert all(len(set(cell)) == len(cell)
               for grid in (A, B) for row in grid for cell in row)
    expected = 6 * q * (
        (B_SHAPE[1] + B_SHAPE[0]) * sum(map(sum, sa))
        + (A_SHAPE[1] + A_SHAPE[0]) * sum(map(sum, sb)))
    assert 6 * sum(row.bit_count() for row in hx + hz) == expected
    return {"A": A, "B": B, "k": 195,
            "contract": (acard, bcard, batch),
            "screen": key, "bp_surrogate": (bx, bz),
            "cnots": expected}


