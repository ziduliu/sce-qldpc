def NEW_CTX(rng, G, idx):
    """Degree-three contracts and verified multiqubit fault-class selection."""
    import hashlib
    import random
    from collections import Counter
    from itertools import combinations

    q = G.q
    assert q == 8
    design, batch = idx % 20, idx // 20
    acard, bcard = divmod(design, 4)

    # Each integer gives the upper-row share of a degree-three column.
    # Remaining columns are cross-row degree-two matchings.
    # Start with the balanced A contract, not the heaviest architecture.
    a_briefs = (
        (0, 3),                 # row totals 8/8
        (3,),                   # row totals 9/6
        (1, 3),                 # row totals 9/7
        (0, 1, 3),              # row totals 8/9
        (0, 0, 3, 3),           # row totals 9/9
    )
    b_briefs = (
        (2,),                   # row totals 9/8, seventeen terms
        (0, 3),                 # exclusive triple anchors, eighteen terms
        (0, 3),                 # same counts, different triple geometry
        (1, 2),                 # balanced mixed triples, eighteen terms
    )

    def support(width, brief):
        profile = [(p, 3-p) for p in brief]
        profile += [(1, 1)] * (width-len(brief))
        return [[p[i] for p in profile] for i in range(2)]

    sa = support(7, a_briefs[acard])
    sb = support(8, b_briefs[bcard])
    assert _grid_weights(sa, sb) <= W_MAX
    assert _no_dead_lines(sa, sb)
    assert any(w == 3 for row in sa for w in row)
    assert all(2 <= sum(grid[i][j] for i in range(2)) <= 3
               for grid in (sa, sb) for j in range(len(grid[0])))

    def clone(grid):
        return [[list(cell) for cell in row] for row in grid]

    def columns(rows, width):
        out = [0] * width
        for r, row in enumerate(rows):
            tag = 1 << r
            while row:
                bit = row & -row
                out[bit.bit_length()-1] |= tag
                row ^= bit
        return out

    def component(grid, side):
        # Zero partners are probes, never submitted fillings.
        if side == "A":
            rows = lifted_matrices(G, grid, [[[]]])[0]
        else:
            rows = lifted_matrices(G, [[[]]], grid)[1]
        width = len(grid[0]) * q
        mask = (1 << width)-1
        return [row & mask for row in rows], width

    def component_identity(rows, width):
        """Rooted uncolored invariant, not full-code canonization.

        A component's regular group action is transitive within each
        check-row orbit. The two roots therefore represent the complete
        multiset of check-rooted refinement fingerprints.
        """
        nr = len(rows)
        adjacency = [[] for _ in range(nr+width)]
        for c, value in enumerate(columns(rows, width)):
            while value:
                bit = value & -value
                r = bit.bit_length()-1
                adjacency[r].append(nr+c)
                adjacency[nr+c].append(r)
                value ^= bit

        fingerprints = []
        for root in (0, q):
            colors = [0]*nr + [1]*width
            colors[root] = 2
            digest = hashlib.sha256()
            for _ in range(12):
                signatures = [
                    (colors[v], tuple(sorted(
                        colors[w] for w in adjacency[v])))
                    for v in range(nr+width)
                ]
                digest.update(repr(sorted(
                    Counter(signatures).items())).encode("ascii"))
                palette = {s: t for t, s in enumerate(
                    sorted(set(signatures)))}
                colors = [palette[s] for s in signatures]
            fingerprints.append(digest.hexdigest())
        return nr, width, tuple(sorted(fingerprints))

    rotations = ((1, 0), (3, 0))
    involutions = tuple(g for g in G.elements
                        if g != G.e and G.mul(g, g) == G.e)

    def triple(local_rng, geometry):
        # Different generated subgroups, not translations of one
        # archived complete code: D8, C4, or a Klein four subgroup.
        u = local_rng.choice((1, 3))
        v = local_rng.randrange(4)
        if geometry == 0:
            return [G.e, (u, 0), (v, 1)]
        if geometry == 1:
            return [G.e, (u, 0), (2, 0)]
        return [G.e, (2, 0), (v, 1)]

    def draw(local_rng, counts, geometry, ratio_kind):
        width = len(counts[0])
        grid = [[[] for _ in range(width)] for _ in range(2)]
        matching = [j for j in range(width)
                    if counts[0][j] == counts[1][j] == 1]
        voltages = local_rng.sample(G.elements, len(matching))
        for j, voltage in zip(matching, voltages):
            grid[0][j], grid[1][j] = [G.e], [voltage]

        palette = rotations if ratio_kind == 0 else involutions
        for j in range(width):
            if j in matching:
                continue
            for i in range(2):
                weight = counts[i][j]
                if weight == 3:
                    grid[i][j] = triple(local_rng, geometry)
                elif weight == 2:
                    base = G.e if i == 0 else local_rng.choice(G.elements)
                    d = local_rng.choice(palette)
                    grid[i][j] = [base, G.mul(base, d)]
                elif weight == 1:
                    grid[i][j] = [
                        G.e if i == 0 else local_rng.choice(G.elements)]
        return grid

    def bank(side, brief_number):
        counts = sa if side == "A" else support(
            8, b_briefs[brief_number])
        # Briefs 1/2 share counts but not their relative geometry.
        geometry = (
            (0, 0, 1, 2)[brief_number] if side == "A"
            else (0, 0, 2, 1)[brief_number])
        ratio_kind = int(brief_number >= 2)
        seed = (82728019 + 1009*acard + 65537*brief_number
                + 104729*(side == "B"))
        local_rng = random.Random(seed)
        entries = {}

        for trial in range(512):
            grid = draw(local_rng, counts, geometry, ratio_kind)
            rows, width = component(grid, side)
            stats = _kernel_statistics(rows, width)
            if stats[0] or gf2_rank(rows) != 2*q:
                continue
            coarse = (
                stats[1], stats[2], stats[3],
                _four_cycles(rows), _six_cycles(rows))
            if len(entries) >= 16:
                worst = max(item[0] for item in entries.values())
                if coarse > worst:
                    continue
            identity = component_identity(rows, width)
            item = (coarse, identity, trial, clone(grid))
            old = entries.get(identity)
            if old is None or item[:3] < old[:3]:
                entries[identity] = item
            if len(entries) > 16:
                ordered = sorted(entries.values(), key=lambda x: x[:3])
                entries = {item[1]: item for item in ordered[:16]}

        result = sorted(entries.values(), key=lambda x: x[:3])[:10]
        if not result:
            raise ValueError("No distinct full-rank triple-contract component")
        return result

    # Rebuild only contracts that could share the same count invariant.
    # All state is local; later calls reconstruct the same reservations.
    related = (0,) if bcard == 0 else (1, 2, 3)
    catalogues = {}
    for brief_number in related:
        aa, bb = bank("A", brief_number), bank("B", brief_number)
        unique = {}
        for a in aa:
            for b in bb:
                coarse = tuple(
                    value for t in range(5)
                    for value in (max(a[0][t], b[0][t]),
                                  a[0][t]+b[0][t]))
                identity = (a[1], b[1])
                item = (coarse, identity, a[3], b[3])
                old = unique.get(identity)
                if old is None or coarse < old[0]:
                    unique[identity] = item
        catalogues[brief_number] = sorted(
            unique.values(), key=lambda item: item[:2])

    reserved = set()
    chosen = None
    for slot in range(idx+1):
        previous_design = slot % 20
        previous_a, previous_b = divmod(previous_design, 4)
        if previous_a != acard or previous_b not in related:
            continue
        available = [
            item for item in catalogues[previous_b]
            if item[1] not in reserved]
        if not available:
            raise ValueError("Unused component-class pairs exhausted")
        finalists = available[:3]
        reserved.update(item[1] for item in finalists)
        if slot == idx:
            chosen = finalists
    assert chosen

    def quotient_columns(stabilizers, width):
        """Linear remainders modulo the actual stabilizer row span."""
        pivots = {}
        for row in stabilizers:
            while row:
                p = row.bit_length()-1
                old = pivots.get(p)
                if old is None:
                    pivots[p] = row
                    break
                row ^= old
        residual = [0]*width
        for c in range(width):
            row = pivots.get(c)
            if row is None:
                residual[c] = 1 << c
                continue
            tail, value = row ^ (1 << c), 0
            while tail:
                bit = tail & -tail
                value ^= residual[bit.bit_length()-1]
                tail ^= bit
            residual[c] = value
        return residual

    def spread_class_cost(checks, stabilizers, width):
        """Enumerated fault-class ambiguity, NOT an ASC simulation.

        Independent data pairs and possible opposite-check pairs/triples
        compete in actual syndrome/stabilizer-quotient buckets. Uniform
        subsets deliberately avoid claiming a particular hook ordering.
        Integer masses approximate exposure, not calibrated probabilities.
        """
        syndrome = columns(checks, width)
        opposite = columns(stabilizers, width)
        if 0 in syndrome or len(set(syndrome)) != width:
            return None
        residual = quotient_columns(stabilizers, width)
        exposure = [1+s.bit_count()+h.bit_count()
                    for s, h in zip(syndrome, opposite)]
        buckets = {0: {0: 1000000000}}

        def add(value, label, mass):
            classes = buckets.setdefault(value, {})
            classes[label] = classes.get(label, 0)+mass

        for i, value in enumerate(syndrome):
            add(value, residual[i], 8000*exposure[i])
        for i, si in enumerate(syndrome):
            ri = residual[i]
            for j in range(i):
                add(si ^ syndrome[j], ri ^ residual[j],
                    64*exposure[i]*exposure[j])

        for row in stabilizers:
            sites = []
            while row:
                bit = row & -row
                sites.append(bit.bit_length()-1)
                row ^= bit
            weight = len(sites)
            if weight < 2:
                continue
            pairs = weight*(weight-1)//2
            pair_mass = max(1, 3200*weight//pairs)
            for a, b in combinations(sites, 2):
                add(syndrome[a] ^ syndrome[b],
                    residual[a] ^ residual[b], pair_mass)
            if weight >= 3:
                triples = weight*(weight-1)*(weight-2)//6
                triple_mass = max(1, 3200*weight//triples)
                for a, b, c in combinations(sites, 3):
                    add(syndrome[a] ^ syndrome[b] ^ syndrome[c],
                        residual[a] ^ residual[b] ^ residual[c],
                        triple_mass)

        loss = peak = ambiguous = 0
        spectrum = Counter()
        for classes in buckets.values():
            if len(classes) <= 1:
                continue
            error = sum(classes.values())-max(classes.values())
            loss += error
            peak = max(peak, error)
            ambiguous += 1
            spectrum[error] += 1
        return loss, peak, ambiguous, tuple(sorted(spectrum.items()))

    winner = None
    seen_channels = set()
    for coarse, identity, A, B in chosen:
        hx, hz, n = lifted_matrices(G, A, B)
        k = n-gf2_rank(hx)-gf2_rank(hz)
        if n != 480 or k != 240:
            continue
        pz = spread_class_cost(hx, hz, n)
        px = spread_class_cost(hz, hx, n)
        if px is None or pz is None:
            continue
        channel_identity = tuple(sorted((px, pz)))
        if channel_identity in seen_channels:
            continue
        seen_channels.add(channel_identity)
        score = tuple(
            value for t in range(3)
            for value in (max(px[t], pz[t]), px[t]+pz[t]))
        score += coarse
        if winner is None or score < winner[0]:
            winner = (score, A, B, hx, hz, identity, px, pz)

