def _component_rows(hx, hz, q):
    """Extract components from the verified lift, never rebuild a lift."""
    ra, ca = A_SHAPE
    rb, cb = B_SHAPE
    mask = (1 << q) - 1
    ar = []
    for i in range(ra):
        for t in range(q):
            row = hx[(i * cb) * q + t]
            ar.append(sum(((row >> (j * cb * q)) & mask) << (j * q)
                          for j in range(ca)))
    bmask = (1 << (cb * q)) - 1
    br = [row & bmask for row in hz[:rb * q]]
    return ar, br


def _four_cycles(rows):
    return sum((v * (v - 1)) // 2
               for i, row in enumerate(rows)
               for other in rows[:i]
               for v in [(row & other).bit_count()])


def _six_cycles(rows):
    """Count cycles using three checks and three distinct data columns."""
    m = len(rows)
    overlap = [[0] * m for _ in range(m)]
    for i in range(m):
        for j in range(i):
            overlap[i][j] = overlap[j][i] = (
                rows[i] & rows[j]).bit_count()
    total = 0
    for i in range(m):
        for j in range(i):
            x = overlap[i][j]
            if not x:
                continue
            common = rows[i] & rows[j]
            for h in range(j):
                y, z = overlap[j][h], overlap[i][h]
                if y and z:
                    triple = (common & rows[h]).bit_count()
                    total += x * y * z - triple * (x + y + z) + 2 * triple
    return total


def _small_kernel_word(rows, ncols):
    """Exact meet-in-the-middle test for a nonzero kernel word <=6."""
    columns = [0] * ncols
    for r, row in enumerate(rows):
        bit = 1 << r
        while row:
            low = row & -row
            columns[low.bit_length() - 1] |= bit
            row ^= low

    # Each subset of size <=3 is visited once. Equal syndromes of two
    # different subsets give a nonzero kernel word of weight <=6.
    seen = {0}
    for value in columns:
        if value in seen:
            return True
        seen.add(value)
    for i in range(ncols):
        for j in range(i):
            value = columns[i] ^ columns[j]
            if value in seen:
                return True
            seen.add(value)
    for i in range(ncols):
        for j in range(i):
            pair = columns[i] ^ columns[j]
            for h in range(j):
                value = pair ^ columns[h]
                if value in seen:
                    return True
                seen.add(value)
    return False


def NEW_CTX(rng, G, idx):
    """Optimize a deliberate support design on the verified order-36 lift."""
    design = idx % len(_PROFILE_PAIRS)
    pa, pb = _PROFILE_PAIRS[design]
    profiles = (_SUPPORT_PROFILES_A[pa], _SUPPORT_PROFILES_B[pb])
    shapes = (A_SHAPE, B_SHAPE)
    counts = [
        [[p[cols * i + j] for j in range(cols)] for i in range(rows)]
        for p, (rows, cols) in zip(profiles, shapes)
    ]
    assert _grid_weights(counts[0], counts[1]) <= W_MAX
    assert _no_dead_lines(counts[0], counts[1])
    assert all(0 <= c <= CELL_MAX for grid in counts for row in grid for c in row)

    # Ban relative orders 1, 2 and 3 within a cell. This also guarantees
    # distinct labels. All subsequent matrix screening uses scaffold lifts.
    blocked = [set() for _ in G.elements]
    for a, g in enumerate(G.elements):
        gi = G.inv(g)
        for b, h in enumerate(G.elements):
            rel = G.mul(gi, h)
            square = G.mul(rel, rel)
            if square == G.e or G.mul(square, rel) == G.e:
                blocked[a].add(b)

    def draw(count):
        available = list(range(G.q))
        cell = []
        for _ in range(count):
            label = rng.choice(available)
            cell.append(G.elements[label])
            available = [a for a in available if a not in blocked[label]]
        return cell

    fallback = None
    for batch in range(4):
        pool = []
        for trial in range(64):
            grids = [
                [[draw(counts[s][i][j]) for j in range(cols)]
                 for i in range(rows)]
                for s, (rows, cols) in enumerate(shapes)
            ]
            A, B = grids
            hx, hz, n = lifted_matrices(G, A, B)
            k = n - gf2_rank(hx) - gf2_rank(hz)
            # Strictly inside the 0.150 cell, not on its lower tie boundary.
