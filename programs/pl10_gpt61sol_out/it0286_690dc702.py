def _pc_labels(rng, G, binomial, brief):
    """Long binomial and two fresh noncommuting quotient triangles."""
    # Orders 28, 14 and 7, respectively.
    generator = ((1,2), (1,4), (1,0))[binomial]
    cells = [[G.e, generator]]
    for j, kind in enumerate(brief):
        if kind < 3:
            a = rng.randrange(1, 7)
            # y -> x^v y is a common automorphism fixing the binomial.
            # Normalize only the first odd phase; retain relative phases.
            phase = 0 if j == 0 else rng.randrange(7)
            exponent = (0, 4, 2)[kind]
            u, v = (a, exponent), (phase, 1)
        else:
            a = 0 if j == 0 else rng.randrange(7)
            phase = rng.choice([t for t in range(7) if t != a])
            u, v = (a, 1), (phase, 3)
        assert G.mul(u, v) != G.mul(v, u)
        cell = [G.e, u, v]
        assert len({G.idx(g) for g in cell}) == 3
        cells.append(cell)
    return [cells]


def _pc_label_key(grid, G):
    """Exact trial key; contract invariants remove obvious orbit contracts.

    Arbitrary Tanner equivalence is still the evaluator's responsibility.
    """
    return tuple(tuple(sorted(G.idx(g) for g in cell))
                 for cell in grid[0])


def _pc_columns(rows, n):
    columns = [0] * n
    for r, row in enumerate(rows):
        while row:
            bit = row & -row
            columns[bit.bit_length() - 1] |= 1 << r
            row ^= bit
    return columns


def _pc_four(columns):
    """Reject all component kernels of weights one through four."""
    singles = set(columns)
    if 0 in singles or len(singles) != len(columns):
        return True
    seen = set()
    for i, x in enumerate(columns):
        for j in range(i):
            syndrome = x ^ columns[j]
            if syndrome in singles or syndrome in seen:
                return True
            seen.add(syndrome)
    return False


def _pc_six(columns, q):
    """Exact five/six-word census after kernels through four are excluded.

    Matching pair/triple supports are disjoint and count each five-set
    ten times. Matching distinct triples count each six-set ten times.
    Boundary loads are heuristics, not circuit-failure estimates.
    """
    pairs = {}
    for i, x in enumerate(columns):
        for y in columns[:i]:
            value = x ^ y
            pairs[value] = pairs.get(value, 0) + 1

    triples = {}
    five = six = boundary = 0
    loads = [0] * (len(columns) // q)
    for a in range(len(columns)-2):
        x = columns[a]
        for b in range(a+1, len(columns)-1):
            pair = x ^ columns[b]
            for c in range(b+1, len(columns)):
                value = pair ^ columns[c]
                five += pairs.get(value, 0)
                six += triples.get(value, 0)
                triples[value] = triples.get(value, 0) + 1
                weight = value.bit_count()
                if weight <= 4:
                    cost = (5-weight)**2
                    boundary += cost
                    loads[a//q] += cost
                    loads[b//q] += cost
                    loads[c//q] += cost
    assert five % 10 == 0 and six % 10 == 0
    return five//10, six//10, max(loads), boundary


def _pc_cycles6(columns, m):
    """Tanner six-cycles from the check-intersection graph."""
    adjacency = [0] * m
    for column in columns:
        neighbors = []
        while column:
            bit = column & -column
            neighbors.append(bit.bit_length() - 1)
            column ^= bit
        for i in neighbors:
            for j in neighbors:
                if i != j:
                    adjacency[i] |= 1 << j
    triangles = 0
    for i in range(m):
        for j in range(i + 1, m):
            if (adjacency[i] >> j) & 1:
                triangles += (
                    adjacency[i] & adjacency[j] &
                    ~((1 << (j + 1)) - 1)
                ).bit_count()
    # With no Tanner four-cycles, remove triangles supplied by one
    # variable. This also handles the lighter degree-two policies.
    supplied = 0
    for column in columns:
        degree = column.bit_count()
        supplied += degree * (degree - 1) * (degree - 2) // 6
    return triangles - supplied


