def _pc_select(rng, G, side, binomial, brief, actions):
    """Independent searches using only helper-derived component actions."""
    q, width = G.q, 3*G.q
    pool, seen = [], set()
    accepted = 0

    def component(grid):
        rows = [0]*q
        for j, cell in enumerate(grid[0]):
            for g in cell:
                block = actions[G.idx(g)]
                for r, value in enumerate(block):
                    rows[r] ^= value << (j*q)
        return rows

    def connected_and_clean(rows):
        adjacency = [0]*q
        for i, row in enumerate(rows):
            for j in range(i):
                common = (row & rows[j]).bit_count()
                if common > 1:
                    return False
                if common:
                    adjacency[i] |= 1 << j
                    adjacency[j] |= 1 << i
        reached, todo = {0}, [0]
        while todo:
            bits = adjacency[todo.pop()]
            while bits:
                bit = bits & -bits
                v = bit.bit_length()-1
                bits ^= bit
                if v not in reached:
                    reached.add(v)
                    todo.append(v)
        return len(reached) == q

    for trial in range(1600):
        grid = _pc_labels(rng, G, binomial, brief)
        identity = _pc_label_key(grid, G)
        if identity in seen:
            continue
        seen.add(identity)
        rows = component(grid)
        if gf2_rank(rows) != q or not connected_and_clean(rows):
            continue
        columns = _pc_columns(rows, width)
        if _pc_four(columns):
            continue
        assert sorted({c.bit_count() for c in columns}) == [2, 3]
        cycles = _pc_cycles6(columns, q)
        assert cycles >= 0
        accepted += 1
        pool.append((cycles, identity, grid, rows, columns))
        pool.sort(key=lambda item: item[:2])
        del pool[4:]
        if accepted >= 48 and trial >= 96:
            break

    if not pool:
        raise ValueError("no clean connected semidirect component")

    refined = []
    for cycles, identity, grid, rows, columns in pool:
        score = _pc_six(columns, q) + (cycles,)
        refined.append((score, identity, grid, rows))
    refined.sort(key=lambda item: item[:2])
    return refined[:2]


def _pc_basis(rows):
    pivots = {}
    for row in rows:
        while row:
            p = row.bit_length() - 1
            if p in pivots:
                row ^= pivots[p]
            else:
                pivots[p] = row
                break
    return pivots


def _pc_in_span(word, pivots):
    while word:
        p = word.bit_length() - 1
        if p not in pivots:
            return False
        word ^= pivots[p]
    return True


def _pc_no_small_logicals(checks, stabilizers, n):
    """Exact weight <=4 logical exclusion on the verified CSS matrices."""
    columns = _pc_columns(checks, n)
    pivots = _pc_basis(stabilizers)

    def logical(word):
        return bool(word) and not _pc_in_span(word, pivots)

    singles = {}
    for i, syndrome in enumerate(columns):
        word = 1 << i
        if syndrome == 0 and logical(word):
            return False
        if syndrome in singles and logical(word ^ singles[syndrome]):
            return False
        singles.setdefault(syndrome, word)
    pairs = {}
    for i, x in enumerate(columns):
        for j in range(i):
            syndrome = x ^ columns[j]
            word = (1 << i) | (1 << j)
            if syndrome == 0 and logical(word):
                return False
            if syndrome in singles and logical(word ^ singles[syndrome]):
                return False
            if syndrome in pairs and logical(word ^ pairs[syndrome]):
                return False
            pairs.setdefault(syndrome, word)
    return True


def _pc_temporal_probe(checks, stabilizers, n, seed, shots):
    """Six-round BP surrogate, NOT an ASC or relay/LSD measurement.

    Includes noisy measurements, degree-weighted data increments and
    approximate correlated pairs drawn from OPPOSITE stabilizer checks.
    The terminal syndrome is perfect; settled residuals are classified
    modulo the actual stabilizer row span.
    """
    import numpy as np

    def neighborhoods(rows):
        result = []
        for row in rows:
            ns = []
            while row:
                bit = row & -row
                ns.append(bit.bit_length()-1)
                row ^= bit
            result.append(ns)
        return result

    neighbors = neighborhoods(checks)
    hooks = neighborhoods(stabilizers)
    m = len(checks)
    rounds = 6
    variables = rounds*(n+m)
    dummy = variables
    row_width = max(map(len, neighbors)) + 2
    incidence = np.full(((rounds+1)*m, row_width), dummy,
                        dtype=np.int32)
    for t in range(rounds+1):
        for r, ns in enumerate(neighbors):
            detector, position = t*m+r, 0
            if t < rounds:
                for c in ns:
                    incidence[detector, position] = t*n+c
                    position += 1
                incidence[detector, position] = rounds*n+t*m+r
                position += 1
            if t:
                incidence[detector, position] = rounds*n+(t-1)*m+r

    flat = incidence.ravel()
    valid = flat != dummy
    edges = len(flat)
    degree = np.bincount(flat[valid], minlength=variables)
    assert np.all(degree > 0)
    variable_edges = np.full(
        (variables+1, int(degree.max())), edges, dtype=np.int32)
    used = np.zeros(variables, dtype=np.int32)
    for edge in np.flatnonzero(valid):
        c = int(flat[edge])
        variable_edges[c, used[c]] = edge
        used[c] += 1

    spatial_degree = np.asarray(
        [c.bit_count() for c in _pc_columns(checks, n)])
    opposite_degree = np.asarray(
        [c.bit_count() for c in _pc_columns(stabilizers, n)])
    data_rate = 0.002*(2+spatial_degree+opposite_degree)
    measurement_rate = np.asarray(
        [0.002*(2+len(ns))*2/3 for ns in neighbors])
    base = np.concatenate((np.tile(data_rate, rounds),
                           np.tile(measurement_rate, rounds)))
    levels = np.asarray((1.0, 1.4, 1.8))[np.arange(shots) % 3]
    rates = np.minimum(levels[:, None]*base[None, :], 0.25)
    channel = np.random.default_rng(seed)
    error = np.zeros((shots, variables+1), dtype=bool)
    error[:, :variables] = channel.random((shots, variables)) < rates

    # These are candidate ancilla-spread pairs, not certified ASC hooks.
    for t in range(rounds):
        selected = channel.integers(len(hooks), size=shots)
        active = channel.random(shots) < 0.20
        for shot in np.flatnonzero(active):
            ns = hooks[int(selected[shot])]
            a = int(channel.integers(len(ns)))
            b = int(channel.integers(len(ns)-1))
            b += b >= a
            error[shot, t*n+ns[a]] ^= True
            error[shot, t*n+ns[b]] ^= True

    detector_count = (rounds+1)*m
    target = (
        error[:, flat].reshape(
            shots, detector_count, row_width).sum(axis=2) & 1
    ).astype(bool)
    target_sign = np.where(target, -1.0, 1.0)
    prior = np.empty((shots, variables+1), dtype=np.float64)
    prior[:, :variables] = np.log((1-rates)/rates)
    prior[:, dummy] = 30.0
    messages = prior[:, flat].copy()
    messages[:, ~valid] = 30.0
    true_final = np.logical_xor.reduce(
        error[:, :rounds*n].reshape(shots, rounds, n), axis=1)
    span = _pc_basis(stabilizers)

    failures = iteration_sum = 0
    for iteration in range(1, 25):
        count = len(prior)
        shaped = messages.reshape(count, detector_count, row_width)
        signs = np.where(shaped < 0, -1.0, 1.0)
        logs = np.log(np.clip(
            np.tanh(np.abs(shaped)/2), 1e-12, 1-1e-8))
        product = np.minimum(
            np.exp(logs.sum(axis=2, keepdims=True)-logs), 1-1e-8)
        outgoing = (
            (np.log1p(product)-np.log1p(-product))
            * signs * signs.prod(axis=2, keepdims=True)
            * target_sign[:, :, None]
        ).reshape(count, edges)
        outgoing[:, ~valid] = 0.0
        padded = np.zeros((count, edges+1), dtype=np.float64)
        padded[:, :edges] = outgoing
        posterior = prior + padded[:, variable_edges].sum(axis=2)
        posterior[:, dummy] = 30.0
        hard = posterior < 0
        syndrome = (
            hard[:, flat].reshape(
                count, detector_count, row_width).sum(axis=2) & 1
        ).astype(bool)
        settled = np.all(syndrome == target, axis=1)
        decoded_final = np.logical_xor.reduce(
            hard[:, :rounds*n].reshape(count, rounds, n), axis=1)
        for local in np.flatnonzero(settled):
            word = 0
            for c in np.flatnonzero(decoded_final[local] ^ true_final[local]):
                word |= 1 << int(c)
            failures += int(not _pc_in_span(word, span))
            iteration_sum += iteration

        keep = ~settled
        if not np.any(keep):
            return failures, 0, iteration_sum
        messages = np.clip(
            0.30*messages + 0.70*(posterior[:, flat]-outgoing),
            -30, 30)[keep]
        messages[:, ~valid] = 30.0
        prior = prior[keep]
        target = target[keep]
        target_sign = target_sign[keep]
        true_final = true_final[keep]

    unresolved = len(prior)
    return failures+unresolved, unresolved, iteration_sum+25*unresolved


