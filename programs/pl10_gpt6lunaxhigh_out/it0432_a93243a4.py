CUSTOM_GROUP = """
def valid_q(q):
    return q == 28

def custom_ops(q):
    # Dic_7 as C7 semidirect C4: y*x*y^-1 = x^-1.
    # Elements (a,b) represent x^a y^b; y has order 4.
    m, r, s = 7, 4, 6
    els = [(a, b) for b in range(r) for a in range(m)]

    def red(g):
        return (int(g[0]) % m, int(g[1]) % r)

    def idx(g):
        a, b = red(g)
        return 4*a + b

    def mul(g, h):
        a, b = red(g)
        c, d = red(h)
        return ((a + pow(s, b, m) * c) % m, (b + d) % r)

    def inv(g):
        a, b = red(g)
        bi = (-b) % r
        return ((-pow(s, bi, m) * a) % m, bi)

    return dict(elements=els, ident=(0, 0), mul=mul, inv=inv,
                idx=idx, red=red)
"""
A0 = None                      # only used by GTYPE = "abelian"

A_SHAPE = (2, 4)               # (ra, ca)
B_SHAPE = (2, 4)               # (rb, cb)


def NEW_CTX(rng, G, idx):
    """Search denser balanced supports and labels with exact lifted checks."""
    def support(rows, cols, total):
        extras = total - rows * cols
        for _ in range(256):
            chosen = rng.sample(range(rows * cols), extras)
            re = [0] * rows
            ce = [0] * cols
            for p in chosen:
                re[p // cols] += 1
                ce[p % cols] += 1
            if max(re) <= 3 and max(ce) <= 2:
                grid = [[1] * cols for _ in range(rows)]
                for p in chosen:
                    grid[p // cols][p % cols] += 1
                return grid
        raise ValueError("could not draw balanced support")

    def logical_floor(checks, stabilizers, n):
        """Least non-stabilizer kernel weight found through weight 3; 4
        means no such operator was found in that range."""
        pivots = {}
        for row in stabilizers:
            x = row
            while x:
                p = x.bit_length() - 1
                if p in pivots:
                    x ^= pivots[p]
                else:
                    pivots[p] = x
                    break

        def in_span(x):
            while x:
                p = x.bit_length() - 1
                if p not in pivots:
                    return False
                x ^= pivots[p]
            return True

        sig = [0] * n
        for ri, row in enumerate(checks):
            bit = 1 << ri
            while row:
                b = row & -row
                sig[b.bit_length() - 1] |= bit
                row ^= b

        buckets = {}
        for col, s in enumerate(sig):
            buckets.setdefault(s, []).append(col)

        for i, s in enumerate(sig):
            if s == 0 and not in_span(1 << i):
                return 1
        for cols in buckets.values():
            for u in range(len(cols)):
                for v in range(u + 1, len(cols)):
                    if not in_span((1 << cols[u]) | (1 << cols[v])):
                        return 2
        for i in range(n):
            for j in range(i + 1, n):
                target = sig[i] ^ sig[j]
                for k in buckets.get(target, ()):
                    if k > j and not in_span((1 << i) | (1 << j) | (1 << k)):
                        return 3
        return 4

    def four_cycles(rows):
        total = 0
        for u, row in enumerate(rows):
            for other in rows[:u]:
                common = _popcount(row & other)
                total += common * (common - 1) // 2
        return total

    def balance(grid):
        rs = [sum(row) for row in grid]
        cs = [sum(grid[i][j] for i in range(len(grid)))
              for j in range(len(grid[0]))]

        def spread(values):
            size, total = len(values), sum(values)
            return sum((size * value - total) ** 2 for value in values)

        return spread(rs) + spread(cs)

    # Slot-indexed totals give deliberate profile variation across the family.
    total_a = 10 + idx % 4
    total_b = 10 + (idx // 4) % 4
    best_key, best_cells = None, None

    for _ in range(16):
        sa = support(A_SHAPE[0], A_SHAPE[1], total_a)
        sb = support(B_SHAPE[0], B_SHAPE[1], total_b)
        A = [[rng.sample(G.elements, sa[i][j]) for j in range(A_SHAPE[1])]
             for i in range(A_SHAPE[0])]
        B = [[rng.sample(G.elements, sb[i][j]) for j in range(B_SHAPE[1])]
             for i in range(B_SHAPE[0])]

        hx, hz, n = lifted_matrices(G, A, B)
        if not css_ok(hx, hz):
            continue
        k = n - gf2_rank(hx) - gf2_rank(hz)
        if k <= 0:
            continue

        dx = logical_floor(hz, hx, n)
        dz = logical_floor(hx, hz, n)
        cycles = four_cycles(hx) + four_cycles(hz)
        imbalance = balance(sa) + balance(sb)
        key = (min(dx, dz), dx + dz, -cycles, -imbalance,
               -abs(k - 112), rng.random())
        if best_key is None or key > best_key:
            best_key = key
            best_cells = {"A": A, "B": B}

    if best_cells is None:
        raise ValueError("no positive-k CSS filling found")
    return {"idx": idx, "cells": best_cells}


def CELL(rng, G, side, i, j, ctx):
    """Return the full, screened cell selected jointly in NEW_CTX."""
    return list(ctx["cells"][side][i][j])

